const DC_CODES: [usize; 2] = [0x5E8, 0x60C];
const DC_LENGTHS: [usize; 2] = [0x600, 0x624];
const AC_CODES: [usize; 2] = [0x8C, 0x3BC];
const AC_LENGTHS: [usize; 2] = [0x1D0, 0x318];
const AC_VALUES: [usize; 2] = [0x274, 0x500];

/// The decoder's state between decodes: the quantization tables at the start of
/// `lbl_80431090` (luma, then chroma, in natural order), the work area (`hsd_804D2E70`'s
/// `JpegWorkData` past its `jmp_buf`, which only its own `longjmp` reads: the macroblock's four
/// luma blocks, Cb and Cr, the block's coefficients and each component's last DC), and the
/// bit reader: the next byte's offset in the stream (`hsd_804D79B8` less `hsd_804D79BC`), the
/// stream's size (`hsd_804D79C0`), the bits left in the byte (`hsd_804D79C4`) and the byte
/// (`hsd_804D79C8`).
#[derive(Clone, Debug, PartialEq, Eq, melee_derive::StateEq)]
pub struct Decoder {
    /// Where the last stream lay (`hsd_804D79BC`), the caller's to set.
    pub start: u32,
    pub quant: Vec<u8>,
    pub luma: Vec<i32>,
    pub cb: Vec<i32>,
    pub cr: Vec<i32>,
    pub coef: Vec<i32>,
    pub prev_dc: [i32; 3],
    pub next: u32,
    pub size: i32,
    pub bits_left: i32,
    pub byte: u8,
}

impl Default for Decoder {
    /// As the boot leaves it: the tables' 0x01s, the rest zero (`.bss`).
    fn default() -> Decoder {
        Decoder {
            start: 0,
            quant: vec![1; 0x80],
            luma: vec![0; 0x100],
            cb: vec![0; 0x40],
            cr: vec![0; 0x40],
            coef: vec![0; 0x40],
            prev_dc: [0; 3],
            next: 0,
            size: 0,
            bits_left: 0,
            byte: 0,
        }
    }
}

/// The stream ran out or broke: the original's `longjmp` back to the decode's start.
struct Stop;

/// `slw`: a shift by a register's low six bits, 0 from 32 on.
fn slw(x: i32, n: i32) -> i32 {
    let n = n as u32 & 0x3F;
    if n >= 32 { 0 } else { x << n }
}

/// A run of the decoder over a stream: `src(i)` is the stream's byte `i` (its size and the
/// byte past it, which the readers may look at), `dst` the image.
struct Run<'a, F: FnMut(u32) -> u8> {
    d: &'a mut Decoder,
    src: F,
    dst: &'a mut [u8],
    /// The stream's width once read, and the macroblocks stored.
    width: i32,
    stored: u32,
}

impl<F: FnMut(u32) -> u8> Run<'_, F> {
    /// A table byte, `lbl_80431090` and what follows it.
    fn table(&self, at: usize) -> u8 {
        if at < 0x80 {
            return self.d.quant[at];
        }
        match TABLES.get(at) {
            Some(&b) => b,
            None => crate::game::code::unported_call(&format!(
                "the JPEG decoder's tables read past lbl_804316B4 ({:#010x})",
                0x8043_1090 + at as u32
            )),
        }
    }

    fn table_u16(&self, at: usize) -> u16 {
        u16::from_be_bytes([self.table(at), self.table(at + 1)])
    }

    /// `hsd_803B5C4C`: `count` bits from the stream, high first, a 0xFF byte taking its
    /// stuffed zero with it; past the stream's end, or a 0xFF followed by anything but zero,
    /// stops the decode. A count of zero reads on until the stream ends.
    #[doc(alias = "hsd_803B5C4C")]
    fn bits(&mut self, count: i32) -> Result<i32, Stop> {
        let mut count = count as u32;
        let mut bits = 0i32;
        loop {
            if self.d.bits_left == 0 {
                self.d.bits_left = 8;
                if i64::from(self.d.next) >= i64::from(self.d.size) {
                    return Err(Stop);
                }
                let b = (self.src)(self.d.next);
                self.d.next += 1;
                self.d.byte = b;
                if b == 0xFF {
                    if (self.src)(self.d.next) != 0 {
                        return Err(Stop);
                    }
                    if i64::from(self.d.next) >= i64::from(self.d.size) {
                        return Err(Stop);
                    }
                    self.d.next += 1;
                }
            }
            bits = bits.wrapping_mul(2);
            if i32::from(self.d.byte) & slw(1, self.d.bits_left - 1) != 0 {
                bits |= 1;
            }
            count = count.wrapping_sub(1);
            self.d.bits_left -= 1;
            if count == 0 {
                return Ok(bits);
            }
        }
    }

    /// `hsd_803B5D70`: a Huffman code of component `component`'s DC (`ac` false) or AC table,
    /// read a bit at a time and matched against the codes of each length in turn: its value,
    /// or 0 past 16 bits.
    #[doc(alias = "hsd_803B5D70")]
    fn huffman(&mut self, ac: bool, component: i32) -> Result<i32, Stop> {
        let k = usize::from(component != 0);
        let (codes, lengths, values) = if ac {
            (AC_CODES[k], AC_LENGTHS[k], AC_VALUES[k])
        } else {
            (DC_CODES[k], DC_LENGTHS[k], DC_VALUES)
        };
        let mut i = 0usize;
        let mut code = 0i32;
        let mut length = 1i32;
        loop {
            code = code.wrapping_mul(2) | self.bits(1)?;
            loop {
                if length == i32::from(self.table(lengths + i)) {
                    if code == i32::from(self.table_u16(codes + 2 * i)) {
                        return Ok(i32::from(self.table(values + i)));
                    }
                    i += 1;
                    continue;
                }
                length += 1;
                if length <= 16 {
                    break;
                }
                return Ok(0);
            }
        }
    }

    /// The coefficient at zigzag place `i`: past the block's 64 places a broken stream reads
    /// on into the DC tables after the order.
    fn zigzag(&self, i: i32) -> usize {
        usize::from(self.table(ZIGZAG + i as usize))
    }

    /// Coefficient `z` set: past the block, the work area's last DCs follow it.
    fn set_coef(&mut self, z: usize, v: i32) {
        match z {
            0..0x40 => self.d.coef[z] = v,
            0x40..0x43 => self.d.prev_dc[z - 0x40] = v,
            _ => crate::game::code::unported_call(&format!(
                "a JPEG block's coefficient {z} (past the decoder's work area)"
            )),
        }
    }

    /// `hsd_803B5EA0`: a block of component `component` into the coefficients: its DC added
    /// to the component's last, then each run of zeros and value in zigzag order to the
    /// block's end or an end of block.
    #[doc(alias = "hsd_803B5EA0")]
    fn block(&mut self, component: i32) -> Result<(), Stop> {
        let c = component as usize;
        let size = self.huffman(false, component)?;
        let dc = if size > 0 {
            let mut v = self.bits(size)?;
            if v & slw(1, size - 1) == 0 {
                v = v.wrapping_sub(slw(1, size).wrapping_sub(1));
            }
            v
        } else {
            0
        };
        self.d.prev_dc[c] = self.d.prev_dc[c].wrapping_add(dc);
        self.d.coef[0] = self.d.prev_dc[c];
        let mut i = 1i32;
        while i < 64 {
            let run = self.huffman(true, component)?;
            if run == 0 {
                while i < 64 {
                    let z = self.zigzag(i);
                    self.set_coef(z, 0);
                    i += 1;
                }
                return Ok(());
            }
            let mut zeros = self.bits(run)?.wrapping_sub(1) as u32;
            while zeros != 0 {
                zeros -= 1;
                let z = self.zigzag(i);
                self.set_coef(z, 0);
                i += 1;
            }
            let size = self.huffman(true, component)?;
            let mut v = self.bits(size)?;
            if v & slw(1, size - 1) == 0 {
                v = v.wrapping_sub(slw(1, size).wrapping_sub(1));
            }
            let z = self.zigzag(i);
            i += 1;
            self.set_coef(z, v);
        }
        Ok(())
    }

    /// The marker `marker` found from the reader's place on, a byte at a time, the reader left
    /// on it; none before the stream's end stops the decode.
    fn find(&mut self, marker: u16) -> Result<(), Stop> {
        loop {
            let at = self.d.next;
            if u16::from_be_bytes([(self.src)(at), (self.src)(at + 1)]) == marker {
                return Ok(());
            }
            self.d.next += 1;
            if i64::from(self.d.next) >= i64::from(self.d.size) {
                return Err(Stop);
            }
        }
    }

    /// A quantization table's 64 bytes, in zigzag order, into table `table` (0 luma, 1
    /// chroma) in natural order.
    fn quant_table(&mut self, table: usize) {
        self.d.next += 5;
        for i in 0..64 {
            let b = (self.src)(self.d.next);
            self.d.next += 1;
            let z = usize::from(self.table(ZIGZAG + i));
            self.d.quant[table * 0x40 + z] = b;
        }
    }

    /// The coefficients dequantized by table `table` into a block, then its inverse DCT.
    fn dequantize(&self, table: usize) -> [i32; 64] {
        let mut block = [0i32; 64];
        for (i, o) in block.iter_mut().enumerate() {
            *o = self.d.coef[i].wrapping_mul(i32::from(self.d.quant[table * 0x40 + i]));
        }
        block
    }

    fn decode(&mut self) -> Result<i32, Stop> {
        self.find(0xFFDB)?;
        self.quant_table(0);
        self.find(0xFFDB)?;
        self.quant_table(1);
        self.find(0xFFC0)?;
        self.d.next += 5;
        let at = self.d.next;
        let height = i32::from(u16::from_be_bytes([(self.src)(at), (self.src)(at + 1)]));
        self.d.next += 2;
        let at = self.d.next;
        let width = i32::from(u16::from_be_bytes([(self.src)(at), (self.src)(at + 1)]));
        self.d.next += 12;
        self.width = width;
        self.find(0xFFDA)?;
        self.d.next += 14;
        let mut y = 0;
        while y < height {
            let mut x = 0;
            while x < width {
                for k in 0..4 {
                    self.block(0)?;
                    let mut b = self.dequantize(0);
                    self.d.luma[64 * k..64 * (k + 1)].copy_from_slice(&b);
                    idct(&mut b);
                    self.d.luma[64 * k..64 * (k + 1)].copy_from_slice(&b);
                }
                self.block(1)?;
                let mut b = self.dequantize(1);
                self.d.cb.copy_from_slice(&b);
                idct(&mut b);
                self.d.cb.copy_from_slice(&b);
                self.block(2)?;
                let mut b = self.dequantize(1);
                self.d.cr.copy_from_slice(&b);
                idct(&mut b);
                self.d.cr.copy_from_slice(&b);
                self.store(x, y, width);
                self.stored += 1;
                x += 16;
            }
            y += 16;
        }
        Ok(width.wrapping_mul(height).wrapping_mul(2))
    }

    /// `fn_803B6820`: the macroblock at (`x`, `y`) into the image, `width` wide in GX's 4 by 4
    /// tiles: the luma back up by 128, each pixel's colour from its luma and the chroma of its
    /// 2 by 2 group.
    #[doc(alias = "fn_803B6820")]
    fn store(&mut self, x: i32, y: i32, width: i32) {
        for v in self.d.luma.iter_mut() {
            *v = v.wrapping_add(0x80);
        }
        let aligned = ((width + 15) / 16) << 4;
        for group_y in 0..2 {
            let mut out = (x / 4) * 16 + (aligned << 2) * (y / 4 + group_y);
            for group_x in 0..2 {
                for tile_y in 0..4 {
                    for tile_x in 0..4 {
                        let chroma = (tile_x >> 1) + group_y * 16 + group_x * 2 + (tile_y & 2) * 4;
                        let luma = (group_x * 4 + (group_y * 4 + tile_y) * 8 + tile_x) as usize;
                        for block in 0..4 {
                            let lum = self.d.luma[luma + 64 * block as usize];
                            let c = (chroma + (block % 2) * 4 + (block / 2) * 32) as usize;
                            let (cr, cb) = (self.d.cr[c], self.d.cb[c]);
                            let at = out + ((block & 1) << 5) + aligned * ((block & 2) << 2);
                            let p = rgb565(lum, cb, cr).to_be_bytes();
                            let at = 2 * at as usize;
                            match self.dst.get_mut(at..at + 2) {
                                Some(o) => o.copy_from_slice(&p),
                                None => crate::game::code::unported_call(
                                    "a JPEG macroblock past its image's buffer",
                                ),
                            }
                        }
                        out += 1;
                    }
                }
            }
        }
    }
}

/// `jpeg_clamp`: a channel's value to 0 to 255, truncated.
fn clamp(v: f64) -> i32 {
    if v < 0.0 {
        return 0;
    }
    if 255.0 < v {
        return 255;
    }
    i32::from(fp::fctiwz(v) as u8)
}

/// `jpeg_store_rgb565`: a pixel from its luma and chroma, as the machine code computes it.
fn rgb565(lum: i32, cb: i32, cr: i32) -> u16 {
    let s = |v: i32| fp::frsp(f64::from(v));
    let red = fp::frsp(fp::fmadd(1.402, f64::from(cr), f64::from(lum)));
    let green = fp::fnmsubs(
        f64::from(0.7139f32),
        s(cr),
        fp::fnmsubs(f64::from(0.3441f32), s(cb), s(lum)),
    );
    let blue = fp::frsp(fp::fnmsub(
        0.0012,
        f64::from(cr),
        fp::fmadds(f64::from(1.7718f32), s(cb), s(lum)),
    ));
    let (r, g, b) = (clamp(red), clamp(green), clamp(blue));
    (((r << 8) & 0xF800) | ((g << 3) & 0x7E0) | (b >> 3)) as u16
}

/// `fn_803B61B4`: an 8 by 8 block's inverse DCT in place, rows then columns, each result a
/// quarter of the transform's (`>> 2`).
#[doc(alias = "fn_803B61B4")]
pub fn idct(w: &mut [i32; 64]) {
    for row in 0..8 {
        idct_pass(w, row * 8, 1);
    }
    for col in 0..8 {
        idct_pass(w, col, 8);
    }
    for v in w.iter_mut() {
        *v >>= 2;
    }
}

/// One pass of [`idct`] over the eight values from `at`, `step` apart, as the machine code
/// computes it. Its constants are the original's doubles.
#[allow(clippy::approx_constant)]
fn idct_pass(w: &mut [i32; 64], at: usize, step: usize) {
    let v = |i: usize| w[at + i * step];
    let d = f64::from;
    let (v0, v1, v2, v3, v4, v5, v6, v7) = (v(0), v(1), v(2), v(3), v(4), v(5), v(6), v(7));
    let odd0 = fp::frsp(fp::fmsub(0.980785, d(v7), fp::fmul(0.19509, d(v1))));
    let odd1 = fp::frsp(fp::fmsub(0.83147, d(v5), fp::fmul(0.55557, d(v3))));
    let odd2 = fp::frsp(fp::fmadd(0.55557, d(v5), fp::fmul(0.83147, d(v3))));
    let odd3 = fp::frsp(fp::fmadd(0.19509, d(v7), fp::fmul(0.980785, d(v1))));
    let even_sum = fp::frsp(fp::fmul(0.707107, d(v0.wrapping_add(v4))));
    let even_diff = fp::frsp(fp::fmul(0.707107, d(v0.wrapping_sub(v4))));
    let pair_sum = fp::fadds(odd0, odd1);
    let pair_diff = fp::fadds(fp::fneg(odd2), odd3);
    let odd_sum = fp::fadds(odd2, odd3);
    let rot_diff = fp::frsp(fp::fmadd(
        fp::fneg(0.92388),
        d(v6),
        fp::fmul(0.382683, d(v2)),
    ));
    let rot_sum = fp::frsp(fp::fmadd(0.382683, d(v6), fp::fmul(0.92388, d(v2))));
    let odd_rot_diff = fp::frsp(fp::fmul(0.707107, fp::fadds(fp::fneg(pair_sum), pair_diff)));
    let even0 = fp::fadds(even_sum, rot_sum);
    let odd_diff = fp::fadds(fp::fneg(odd0), odd1);
    let odd_rot_sum = fp::frsp(fp::fmul(0.707107, fp::fadds(pair_sum, pair_diff)));
    let even1 = fp::fadds(even_diff, rot_diff);
    let even2 = fp::fsubs(even_diff, rot_diff);
    let even3 = fp::fsubs(even_sum, rot_sum);
    let out = [
        fp::fadds(even0, odd_sum),
        fp::fadds(even1, odd_rot_diff),
        fp::fadds(even2, odd_rot_sum),
        fp::fadds(even3, odd_diff),
        fp::fsubs(even3, odd_diff),
        fp::fsubs(even2, odd_rot_sum),
        fp::fsubs(even1, odd_rot_diff),
        fp::fsubs(even0, odd_sum),
    ];
    for (i, r) in out.into_iter().enumerate() {
        w[at + i * step] = fp::fctiwz(r);
    }
}

/// `hsd_803B6BE4`: a stream of `size` bytes (`src(i)` its byte `i`, read up to one past its
/// end) decoded into `dst`, a GX RGB565 image: its size in bytes (width by height by 2), or 0
/// when the stream ends or breaks before the image does, `dst` keeping the macroblocks
/// written until then.
#[doc(alias = "hsd_803B6BE4")]
pub fn decode(d: &mut Decoder, src: impl FnMut(u32) -> u8, size: i32, dst: &mut [u8]) -> i32 {
    decode_counted(d, src, size, dst).result
}

/// What a decode did: its result, the stream's width and how many macroblocks it stored.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Decoded {
    pub result: i32,
    pub width: i32,
    pub stored: u32,
}

/// [`decode`], with what it stored.
pub fn decode_counted(
    d: &mut Decoder,
    src: impl FnMut(u32) -> u8,
    size: i32,
    dst: &mut [u8],
) -> Decoded {
    d.size = size;
    d.next = 0;
    d.prev_dc = [0; 3];
    d.bits_left = 0;
    let mut run = Run {
        d,
        src,
        dst,
        width: 0,
        stored: 0,
    };
    let result = run.decode().unwrap_or(0);
    Decoded {
        result,
        width: run.width,
        stored: run.stored,
    }
}

/// The bytes of a `width` wide image (GX's 4 by 4 tiles of 2 bytes) its first `stored`
/// macroblocks cover, as spans (from, to), a tile row of a macroblock each.
pub fn stored_spans(width: i32, stored: u32) -> Vec<(u32, u32)> {
    let per_row = ((width + 15) / 16).max(1) as u32;
    let tiles = per_row * 4;
    let mut v = Vec::new();
    for m in 0..stored {
        let (x, y) = ((m % per_row) * 4, (m / per_row) * 4);
        for r in 0..4 {
            let lo = ((y + r) * tiles + x) * 32;
            v.push((lo, lo + 128));
        }
    }
    v
}
