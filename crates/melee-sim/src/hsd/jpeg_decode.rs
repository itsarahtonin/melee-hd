//! HAL's JPEG decoder (`sysdolphin/baselib/hsd_3B5C.c`), which the album decodes a snapshot
//! read from the card with (`lbSnap_8001DE8C`): the counterpart of [`super::jpeg`]'s encoder.
//! It reads the two quantization tables and the frame's size from the stream, ignores its
//! Huffman tables for its own (the standard ones), and writes each 16 by 16 macroblock into a
//! GX RGB565 image as it decodes it.
//!
//! Its statics are state: the quantization tables it reads go into the start of its tables
//! (`lbl_80431090`, 0x01s at boot), and its work area (`hsd_804D2E70`'s blocks and DCs) and
//! bit reader (`hsd_804D79B8` to `hsd_804D79C8`) keep what the last decode left. A stream that
//! ends early stops the decode where it was (the original's `longjmp`), the image keeping the
//! macroblocks written so far.

