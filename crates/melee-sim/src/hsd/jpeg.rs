/// The output ran past its room: the original's `longjmp` back to the encoder's start.
struct Full;

/// The encoder's state (`hsd_804D2648`, a `JpegWork`, and the writer's statics
/// `hsd_804D79A0` to `hsd_804D79B0`): the output and its room, the bit writer, the blocks being
/// worked on and each component's last DC.
struct Encoder {
    out: Vec<u8>,
    room: usize,
    bits: u8,
    nbits: i32,
    /// `x118`: the macroblock's four luma blocks; `x518`, `x618`: Cb and Cr; `coef`: the
    /// quantized block being written.
    luma: [i32; 0x100],
    cb: [i32; 0x40],
    cr: [i32; 0x40],
    coef: [i32; 0x40],
    prev_dc: [i32; 3],
    quality: i32,
}

impl Encoder {
    /// `hsd_803B3344`: a byte, if there's room.
    #[doc(alias = "hsd_803B3344")]
    fn byte(&mut self, b: u8) -> Result<(), Full> {
        if self.out.len() < self.room {
            self.out.push(b);
            Ok(())
        } else {
            Err(Full)
        }
    }

    /// `hsd_803B3398`: bytes, if there's more room than they take.
    #[doc(alias = "hsd_803B3398")]
    fn bytes(&mut self, b: &[u8]) -> Result<(), Full> {
        if (self.out.len() as u32) < (self.room as u32).wrapping_sub(b.len() as u32) {
            self.out.extend_from_slice(b);
            Ok(())
        } else {
            Err(Full)
        }
    }

    /// The inline bit writer: `length` bits of `value`, high first, each full byte written
    /// and a 0xFF stuffed with a zero.
    fn put_bits(&mut self, value: i32, length: i32) -> Result<(), Full> {
        for bit in (0..length).rev() {
            self.bits <<= 1;
            self.nbits += 1;
            if value & (1 << bit) != 0 {
                self.bits |= 1;
            }
            if self.nbits == 8 {
                self.byte(self.bits)?;
                if self.bits == 0xFF {
                    self.byte(0)?;
                }
                self.nbits = 0;
                self.bits = 0;
            }
        }
        Ok(())
    }

    /// `hsd_803B46D4`: the JFIF header (version 1.2, 72 by 72 dots an inch, no thumbnail).
    #[doc(alias = "hsd_803B46D4")]
    fn jfif(&mut self) -> Result<(), Full> {
        for b in [0xFF, 0xE0, 0, 0x10] {
            self.byte(b)?;
        }
        // The identifier's five bytes need more room than they take.
        if self.out.len() + 5 < self.room {
            self.out.extend_from_slice(b"JFIF\0");
        } else {
            return Err(Full);
        }
        for b in [1, 2, 1, 0, 0x48, 0, 0x48, 0, 0] {
            self.byte(b)?;
        }
        Ok(())
    }

    /// `hsd_803B4A2C`: the two quantization tables in zigzag order, each divided by the
    /// quality.
    #[doc(alias = "hsd_803B4A2C")]
    fn quant_tables(&mut self) -> Result<(), Full> {
        for (id, base) in [(0u8, 0usize), (1, 0x40)] {
            for b in [0xFF, 0xDB, 0, 0x43, id] {
                self.byte(b)?;
            }
            for &z in &ZIGZAG {
                let v = i32::from(TABLES[base + usize::from(z)]) / self.quality;
                self.byte(v as u8)?;
            }
        }
        Ok(())
    }

    /// `hsd_803B4D64`: the frame's header (baseline, 8 bits, `height` by `width`, Y at 2 by 2
    /// with table 0, Cb and Cr at 1 by 1 with table 1).
    #[doc(alias = "hsd_803B4D64")]
    fn frame_header(&mut self, width: u32, height: u32) -> Result<(), Full> {
        let h = [(height >> 8) as u8, height as u8];
        let w = [(width >> 8) as u8, width as u8];
        for b in [0xFF, 0xC0, 0, 0x11, 8, h[0], h[1], w[0], w[1], 3] {
            self.byte(b)?;
        }
        for b in [0, 0x22, 0, 1, 0x11, 1, 2, 0x11, 1] {
            self.byte(b)?;
        }
        Ok(())
    }

    /// `hsd_803B3408`: the 16 by 16 macroblock at (`x`, `y`) of a GX RGB565 image `width`
    /// wide (4 by 4 tiles, big-endian pixels) into the luma blocks, less 128, and the chroma
    /// blocks from every other pixel.
    #[doc(alias = "hsd_803B3408")]
    fn macroblock(&mut self, image: &[u8], x: i32, y: i32, width: i32) {
        let px = |i: i32| u16::from_be_bytes([image[2 * i as usize], image[2 * i as usize + 1]]);
        let rgb = |p: u16| {
            let r = fp::frsp(f64::from((p >> 8) & 0xF8));
            let g = fp::frsp(f64::from((p >> 3) & 0xFC));
            let b = fp::frsp(f64::from((p << 3) & 0xF8));
            (r, g, b)
        };
        let c = |v: f32| fp::lfs(v.to_bits());
        let stride = ((width + 0xF) / 16) << 6;
        let offset = (x / 4) * 0x10 + (y / 4) * stride;
        for tile_y in 0..2 {
            let mut src = offset + tile_y * stride;
            for tile_x in 0..2 {
                let tile = tile_y * 16 + tile_x * 2;
                for cy in 0..4 {
                    let dst_row = tile + (cy & 1) * 4 + (cy & 2) * 16;
                    let src_row = (cy & 1) * 32 + (cy & 2) * stride;
                    for cx in 0..4 {
                        let ci = (cx & 1) + (cx & 2) * 4;
                        let p = px(src + (cx & 1) * 2 + (cx & 2) * 4 + src_row);
                        let (r, g, b) = rgb(p);
                        // Cb: 0.5·B + (-0.1687·R - 0.3313·G), fused as the machine code.
                        let t = fp::fmuls(c(0.3313), g);
                        let t = fp::fmsubs(c(-0.1687), r, t);
                        let t = fp::fmadds(c(0.5), b, t);
                        self.cb[(ci + dst_row) as usize] = fp::fctiwz(t);
                        // Cr: 0.5·R - 0.4187·G - 0.0813·B.
                        let t = fp::fmuls(c(0.4187), g);
                        let t = fp::fmsubs(c(0.5), r, t);
                        let t = fp::fnmsubs(c(0.0813), b, t);
                        self.cr[(ci + dst_row) as usize] = fp::fctiwz(t);
                    }
                }
                for ly in 0..4 {
                    for lx in 0..4 {
                        let base = (tile_x * 4 + ((tile_y * 4 + ly) * 8 + lx)) as usize;
                        for pi in 0..4 {
                            let p = px(src + (pi & 1) * 0x20 + (pi & 2) * stride);
                            let (r, g, b) = rgb(p);
                            // Y: 0.114·B + (0.299·R + 0.587·G).
                            let t = fp::fmuls(c(0.587), g);
                            let t = fp::fmadds(c(0.299), r, t);
                            let t = fp::fmadds(c(0.114), b, t);
                            self.luma[base + pi as usize * 64] = fp::fctiwz(t) - 0x80;
                        }
                        src += 1;
                    }
                }
            }
        }
    }

    /// `hsd_803B3CD8`: the quantized block (`coef`) of component `component` written: its
    /// DC's difference from the last, then each AC's run and size in zigzag order, and an
    /// end of block after a final run of zeros.
    #[doc(alias = "hsd_803B3CD8")]
    fn write_block(&mut self, component: usize) -> Result<(), Full> {
        let table = component.min(1);
        let code = |k: usize, i: usize| {
            u16::from_be_bytes([TABLES[AC_CODE[k] + 2 * i], TABLES[AC_CODE[k] + 2 * i + 1]])
        };
        let len = |k: usize, i: usize| TABLES[AC_LENGTH[k] + i];
        let bit_length = |v: i32| 32 - v.leading_zeros() as i32;
        let mut value = self.coef[0].wrapping_sub(self.prev_dc[component]);
        let length = bit_length(value.wrapping_abs());
        self.prev_dc[component] = self.coef[0];
        self.put_bits(
            i32::from(DC_CODE[table][length as usize]),
            i32::from(DC_LENGTH[table][length as usize]),
        )?;
        if length != 0 {
            if value < 0 {
                value -= 1;
            }
            self.put_bits(value, length)?;
        }
        let mut run = 0;
        for &z in &ZIGZAG[1..] {
            let mut ac = self.coef[usize::from(z)];
            if ac != 0 {
                let length = bit_length(run + 1);
                let i = length as usize;
                self.put_bits(i32::from(code(table, i)), i32::from(len(table, i)))?;
                self.put_bits(run + 1, length)?;
                let length = bit_length(ac.wrapping_abs());
                let i = length as usize;
                self.put_bits(i32::from(code(table, i)), i32::from(len(table, i)))?;
                if ac < 0 {
                    ac -= 1;
                }
                self.put_bits(ac, length)?;
                run = 0;
            } else {
                run += 1;
            }
        }
        if run != 0 {
            self.put_bits(i32::from(code(table, 0)), i32::from(len(table, 0)))?;
        }
        Ok(())
    }

    /// The block quantized into `coef`: each coefficient divided (truncating) by its table's
    /// entry divided by the quality.
    fn quantize(&mut self, block: &[i32; 64], chroma: bool) {
        let q = if chroma { 0x40 } else { 0 };
        for i in 0..64 {
            let d = i32::from(TABLES[q + i]) / self.quality;
            self.coef[i] = block[i] / d;
        }
    }

    fn encode(&mut self, image: &[u8], width: i32, height: i32) -> Result<(), Full> {
        self.byte(0xFF)?;
        self.byte(0xD8)?;
        self.jfif()?;
        let comment_len = COMMENT.len() + 1;
        self.byte(0xFF)?;
        self.byte(0xFE)?;
        let size = comment_len + 2;
        self.byte((size >> 8) as u8)?;
        self.byte(size as u8)?;
        let mut comment = COMMENT.to_vec();
        comment.push(0);
        self.bytes(&comment)?;
        self.quant_tables()?;
        for (class_id, table) in [
            (0x00u8, &HUFF_DC_LUMA[..]),
            (0x01, &HUFF_DC_CHROMA[..]),
            (0x10, &HUFF_AC_LUMA[..]),
            (0x11, &HUFF_AC_CHROMA[..]),
        ] {
            let len = (table.len() + 3) as u8;
            for b in [0xFF, 0xC4, 0, len, class_id] {
                self.byte(b)?;
            }
            self.bytes(table)?;
        }
        self.frame_header(width as u32, height as u32)?;
        for b in [0xFF, 0xDA, 0, 0xC, 3, 0, 0, 1, 0x11, 2, 0x11, 0, 0x3F, 0] {
            self.byte(b)?;
        }
        for y in (0..height).step_by(16) {
            for x in (0..width).step_by(16) {
                self.macroblock(image, x, y, width);
                for k in 0..4 {
                    let mut block = [0i32; 64];
                    block.copy_from_slice(&self.luma[64 * k..64 * (k + 1)]);
                    dct(&mut block);
                    self.luma[64 * k..64 * (k + 1)].copy_from_slice(&block);
                    self.quantize(&block, false);
                    self.write_block(0)?;
                }
                let mut cb = self.cb;
                dct(&mut cb);
                self.cb = cb;
                self.quantize(&cb, true);
                self.write_block(1)?;
                let mut cr = self.cr;
                dct(&mut cr);
                self.cr = cr;
                self.quantize(&cr, true);
                self.write_block(2)?;
            }
        }
        if self.nbits != 0 {
            let pad = 8 - self.nbits;
            self.bits <<= pad;
            self.bits |= ((1i32 << pad) - 1) as u8;
            self.byte(self.bits)?;
            self.bits = 0;
            self.nbits = 0;
        }
        self.byte(0xFF)?;
        self.byte(0xD9)?;
        Ok(())
    }
}

/// `fn_803B376C`: an 8 by 8 block's forward DCT in place, rows then columns, each result a
/// quarter of the transform's (`>> 2`).
#[doc(alias = "fn_803B376C")]
pub fn dct(w: &mut [i32; 64]) {
    for row in 0..8 {
        dct_pass(w, row * 8, 1);
    }
    for col in 0..8 {
        dct_pass(w, col, 8);
    }
    for v in w.iter_mut() {
        *v >>= 2;
    }
}

/// One pass of [`dct`] over the eight values from `at`, `step` apart, as the machine code
/// computes it. Its constants are the original's doubles (0.707107, not 1/√2's).
#[allow(clippy::approx_constant)]
fn dct_pass(w: &mut [i32; 64], at: usize, step: usize) {
    let v = |i: usize| w[at + i * step];
    let s = |x: i32| fp::frsp(f64::from(x));
    let (w0, w1, w2, w3, w4, w5, w6, w7) = (v(0), v(1), v(2), v(3), v(4), v(5), v(6), v(7));
    let a0 = s(w0.wrapping_add(w7));
    let a1 = s(w1.wrapping_add(w6));
    let a2 = s(w2.wrapping_add(w5));
    let a3 = s(w3.wrapping_add(w4));
    let a12 = fp::fadds(a1, a2);
    let a03 = fp::fadds(a0, a3);
    let d03 = fp::fsubs(a0, a3);
    let even0 = fp::fadds(a03, a12);
    let even4 = fp::fsubs(a03, a12);
    let p6 = fp::fmul(0.382683, d03);
    let r0 = fp::fmul(0.707107, even0);
    let d12 = fp::fsubs(a1, a2);
    let r4 = fp::fmul(0.707107, even4);
    let p2 = fp::fmul(0.92388, d03);
    let r6 = fp::fmadd(-0.92388, d12, p6);
    let r2 = fp::fmadd(0.382683, d12, p2);
    let d3 = s(w3.wrapping_sub(w4));
    let d2 = s(w2.wrapping_sub(w5));
    let d1 = s(w1.wrapping_sub(w6));
    let d0 = s(w0.wrapping_sub(w7));
    let sum = fp::fadds(d2, d1);
    let diff = fp::fsubs(d2, d1);
    let m = fp::frsp(fp::fmul(0.707107, sum));
    let n = fp::frsp(fp::fmul(0.707107, diff));
    let b0 = fp::fadds(m, d0);
    let b1 = fp::fadds(fp::fneg(d3), n);
    let b2 = fp::fadds(fp::fneg(m), d0);
    let b3 = fp::fadds(d3, n);
    let r7 = fp::fmadd(0.980785, b1, fp::fmul(0.19509, b0));
    let r5 = fp::fmadd(0.83147, b3, fp::fmul(0.55557, b2));
    let r3 = fp::fmadd(-0.55557, b3, fp::fmul(0.83147, b2));
    let r1 = fp::fmadd(-0.19509, b1, fp::fmul(0.980785, b0));
    let out = [r0, r1, r2, r3, r4, r5, r6, r7];
    for (i, r) in out.into_iter().enumerate() {
        w[at + i * step] = fp::fctiwz(r);
    }
}

/// `hsd_803B51C8`: a `width` by `height` GX RGB565 image compressed at `quality`
/// (`hsd_803B5C2C`'s factor) into at most `room` bytes. The bytes written, and their count, or
/// 0 when they didn't fit (the bytes written until then stay in the output).
#[doc(alias = "hsd_803B51C8")]
pub fn encode(image: &[u8], width: i32, height: i32, room: usize, quality: i32) -> (u32, Vec<u8>) {
    let mut e = Encoder {
        out: Vec::with_capacity(room.min(0x40000)),
        room,
        bits: 0,
        nbits: 0,
        luma: [0; 0x100],
        cb: [0; 0x40],
        cr: [0; 0x40],
        coef: [0; 0x40],
        prev_dc: [0; 3],
        quality,
    };
    match e.encode(image, width, height) {
        Ok(()) => (e.out.len() as u32, e.out),
        Err(Full) => (0, e.out),
    }
}

/// `hsd_803B5C2C`: the quality factor, 3 when out of 1 to 10.
#[doc(alias = "hsd_803B5C2C")]
pub fn quality(q: i32) -> i32 {
    if !(1..=10).contains(&q) { 3 } else { q }
}
