#[cfg(test)]
mod tests {
    /// Against the disc itself, when one is given: every file's offset is the table's.
    #[test]
    fn the_table_is_the_discs() {
        let Ok(path) = std::env::var("SSBM_DISC") else {
            eprintln!("skipped: SSBM_DISC names no disc");
            return;
        };
        let disc = melee_data::disc::Disc::open(&path).expect("the disc");
        let mut files = 0;
        for name in disc.files().expect("the disc's files") {
            let (entrynum, _) = disc.file_info(&name).expect("the file");
            let at = disc.file_offset(&name).expect("the file's offset");
            assert_eq!(super::OFFSETS[entrynum as usize], at, "{name}");
            files += 1;
        }
        assert_eq!(files, 1209);
    }
}
