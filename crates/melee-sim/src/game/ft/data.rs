//! Fighter data (`ftdata.c`): each character's files and tables, the files a fighter's
//! creation finds loaded, and the animation buffers fighters copy their animations into.
//!
//! Disc loads finish outside the simulation (`docs/architecture.md`): the frontend loads a
//! character's files before the match needs them, as the original's preloading does, and
//! hands them over in [`LoadedFiles`]; where the original would read the disc mid-tick
//! (`lbArchive_80017040` finding a file not preloaded), the file must already be there.

use melee_data::archive::{ArchiveId, Archives, DataRef};

use super::super::handles::{AnimBufId, FighterId};
use super::super::mirror::{Cx, Mem, Mirror};
use super::super::state::{Game, Running};
use super::AnimFile;
use super::kind_tables::KINDS;

/// How many fighter kinds there are (`Ft_Kind_Max`).
pub const KIND_COUNT: usize = 33;

/// The size of a fighter's attribute block (`fighter_dat_attrs_alloc_data`).
pub const FIGHTER_ATTRS_SIZE: usize = 0x424;

/// The most costumes a character has.
pub const MAX_COSTUMES: usize = 6;

/// A costume's file and the symbols of its model and material animation
/// (`Fighter_CostumeStrings`).
#[derive(Clone, Copy, Debug)]
pub struct CostumeFiles {
    pub file: Option<&'static str>,
    pub joint: Option<&'static str>,
    pub matanim: Option<&'static str>,
}

/// A fighter kind's tables in the executable, generated by `tools/tables/fighter_files.py`.
#[derive(Clone, Copy, Debug)]
pub struct KindTables {
    /// Its data file and the `ftData` symbol in it (`ftData_803C1F40`).
    pub dat_file: Option<&'static str>,
    pub data_symbol: Option<&'static str>,
    /// `CostumeListsForeachCharacter[kind].numCostumes`.
    pub costume_count: u8,
    /// `ftData_803C2360[kind]`.
    pub costumes: &'static [CostumeFiles],
    /// Its animation file (`ftData_803C23E4`) and how many animations it has
    /// (`ftData_Table_Unk0[kind].count`).
    pub anim_file: Option<&'static str>,
    pub anim_count: u32,
    /// Its effect file's number (`ftData_UnkBytePerCharacter`), 0xFF for none.
    pub effect_file: u8,
    /// Its action-state table (`ftData_CharacterStateTables`).
    pub state_table: u32,
    /// Its callbacks, by address (0 for none): the fighters' first setup's
    /// (`ftData_Table_Unk1`), creation's (`ftData_OnLoad`), a spawn's (`ftData_OnDeath`)
    /// and the attribute changes' (`ftKindCalcIndiviParamTable`).
    pub on_first_init: u32,
    pub on_load: u32,
    pub on_death: u32,
    pub load_special_attrs: u32,
}

/// The destination a fighter file's load into main memory names: the heap isn't modeled, so
/// its address there isn't known; any main-memory address makes the load a disc read.
pub const MAIN_MEMORY: u32 = 0x8000_0000;

/// A fighter kind's tables.
pub fn kind_tables(kind: i32) -> &'static KindTables {
    &KINDS[usize::try_from(kind).expect("a negative fighter kind")]
}

/// A costume's loaded model (`UnkCostumeStruct`): its joint and material animation, which
/// `ftData_80085820` finds in the costume's file, and a word the fighters' first setup clears.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Costume {
    pub joint: Option<DataRef>,
    pub matanim: Option<DataRef>,
    pub x8: u32,
}

/// The disc files the frontend has loaded for the fighter code, by name: archives in main
/// memory, and animation files in ARAM with the address it put each at.
#[derive(melee_derive::CloneFrom, Debug, Default, PartialEq)]
pub struct LoadedFiles {
    #[clone_from(if_changed)]
    pub archives: Vec<(String, ArchiveId)>,
    #[clone_from(if_changed)]
    pub anim_files: Vec<(String, AnimFile)>,
    /// Each file's disc entry number and size, for the disc loads the audio timeline times.
    #[clone_from(if_changed)]
    pub entries: Vec<(String, i32, u32)>,
}

impl LoadedFiles {
    /// The loaded archive named `name`.
    pub fn archive(&self, name: &str) -> ArchiveId {
        self.archives
            .iter()
            .find(|(n, _)| n == name)
            .map(|&(_, id)| id)
            .unwrap_or_else(|| {
                panic!("{name} isn't loaded: the frontend loads it before the match")
            })
    }

    /// The disc entry number and size of the file named `name`.
    pub fn entry(&self, name: &str) -> (i32, u32) {
        self.entries
            .iter()
            .find(|(n, ..)| n == name)
            .map(|&(_, e, len)| (e, len))
            .unwrap_or_else(|| panic!("{name}'s disc entry isn't known"))
    }

    /// The animation file named `name`, in ARAM.
    pub fn anim_file(&self, name: &str) -> &AnimFile {
        self.anim_files
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, f)| f)
            .unwrap_or_else(|| {
                panic!("{name} isn't in ARAM: the frontend loads it before the match")
            })
    }
}

/// `ft_8045993C`: six words, each with two bitfields beside it, which the fighters' first
/// setup clears.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Ft8045993C {
    pub x0: u32,
    /// The byte at +6: `x6_b0` (0x80) and `x6_b1_b2` (0x60), and bits nothing names.
    pub x6: u8,
}

/// The fighter data's globals.
#[derive(melee_derive::CloneFrom, Debug, PartialEq)]
pub struct DataGlobals {
    /// The files the frontend has loaded (an input, never compared as state).
    pub files: LoadedFiles,
    /// Each kind's `ftData`, once loaded (`gFtDataList`).
    pub data_list: [Option<DataRef>; KIND_COUNT],
    /// Each kind's costumes' models (`CostumeListsForeachCharacter[kind].costume_list`).
    pub costumes: [[Costume; MAX_COSTUMES]; KIND_COUNT],
    /// Each kind's demo animations' address (`ftData_UnkIntPairs[kind].data`), which the
    /// fighters' first setup clears.
    pub demo_anims: [u32; KIND_COUNT],
    /// Each kind's reference count (`ft_8045996C`).
    pub ref_counts: [i32; KIND_COUNT],
    pub slot_words: [Ft8045993C; 6],
}

impl Default for DataGlobals {
    fn default() -> Self {
        DataGlobals {
            files: LoadedFiles::default(),
            data_list: [None; KIND_COUNT],
            costumes: [[Costume::default(); MAX_COSTUMES]; KIND_COUNT],
            demo_anims: [0; KIND_COUNT],
            ref_counts: [0; KIND_COUNT],
            slot_words: [Ft8045993C::default(); 6],
        }
    }
}

/// Reads a plain struct (no pointers) out of loaded game data, as a struct copy from it does.
pub fn copy_from_data<T: Mirror>(data: &Archives, at: DataRef) -> T {
    let mem = Mem {
        bytes: data.get(at.archive).data(),
        base: 0,
    };
    T::import(&mem, at.offset, &mut NoPointers)
}

/// The [`Cx`] of [`copy_from_data`]: the structs it copies hold no pointers.
struct NoPointers;

impl Cx for NoPointers {
    fn import_handle(&mut self, kind: &'static str, _: u32) -> Option<u32> {
        panic!("a struct copied from game data holds a {kind}")
    }
    fn import_data(&mut self, _: u32) -> Option<DataRef> {
        panic!("a struct copied from game data holds a pointer")
    }
    fn compare_handle(&mut self, _: &str, _: &'static str, _: Option<u32>, _: u32) {
        unreachable!()
    }
    fn compare_data(&mut self, _: &str, _: Option<DataRef>, _: u32) {
        unreachable!()
    }
    fn mismatch(&mut self, _: &str, _: String, _: String) {
        unreachable!()
    }
}

impl Game {
    /// Forgets every kind's data and costumes and the player slots' words, `ft_800852B0`.
    #[doc(alias = "ft_800852B0")]
    pub fn reset_fighter_data(&mut self) {
        self.ft.anim_files.resize(KIND_COUNT, None);
        let d = &mut self.ft.data;
        for (kind, tables) in KINDS.iter().enumerate().take(KIND_COUNT) {
            d.data_list[kind] = None;
            for c in 0..usize::from(tables.costume_count) {
                d.costumes[kind][c].joint = None;
                d.costumes[kind][c].x8 = 0;
            }
            self.ft.anim_files[kind] = None;
            d.demo_anims[kind] = 0;
        }
        for s in &mut d.slot_words {
            s.x0 = 0;
            s.x6 &= !0xE0;
        }
    }

    /// Clears every kind's reference count, `ft_8008549C`.
    #[doc(alias = "ft_8008549C")]
    pub fn reset_fighter_ref_counts(&mut self) {
        self.ft.data.ref_counts = [0; KIND_COUNT];
    }

    /// Finds a kind's `ftData` in its data file unless it has, `ftData_8008572C`.
    #[doc(alias = "ftData_8008572C")]
    pub fn load_fighter_data(&mut self, data: &Archives, kind: i32) -> Option<&'static str> {
        let k = kind as usize;
        if self.ft.data.data_list[k].is_some() {
            return None;
        }
        let t = kind_tables(kind);
        let file = t.dat_file.expect("a fighter kind without a data file");
        let archive = self.ft.data.files.archive(file);
        let symbol = t.data_symbol.expect("a fighter kind without data");
        self.ft.data.data_list[k] = Some(public(data, archive, symbol));
        Some(file)
    }

    /// Finds a costume's model and material animation in its file unless it has,
    /// `ftData_80085820`.
    #[doc(alias = "ftData_80085820")]
    pub fn load_costume(
        &mut self,
        data: &Archives,
        kind: i32,
        costume: i32,
    ) -> Option<&'static str> {
        let (k, c) = (kind as usize, costume as usize);
        if self.ft.data.costumes[k][c].joint.is_some() {
            return None;
        }
        let files = kind_tables(kind).costumes[c];
        let file = files.file.expect("a costume without a file");
        let archive = self.ft.data.files.archive(file);
        let joint = public(
            data,
            archive,
            files.joint.expect("a costume without a model"),
        );
        let entry = &mut self.ft.data.costumes[k][c];
        entry.joint = Some(joint);
        // Without a material animation's name the original passes none, and clears the slot.
        entry.matanim = files.matanim.map(|m| public(data, archive, m));
        Some(file)
    }
}

/// The public symbol `name` of a loaded archive; the original asserts it's there
/// (`vLoadSectionsFatal`).
fn public(data: &Archives, archive: ArchiveId, name: &str) -> DataRef {
    let offset = data
        .get(archive)
        .public(name)
        .unwrap_or_else(|| panic!("the original's assertion failed: Cannot find symbol {name}."));
    DataRef { archive, offset }
}

impl Running<'_> {
    /// Gives the fighter its animation buffers and the kind's animation count, and puts the
    /// kind's animation file in ARAM unless it's there, `ftData_80085B10`.
    #[doc(alias = "ftData_80085B10")]
    pub fn init_anim_buffers(&mut self, f: FighterId) {
        let a = AnimBufId(self.game.fighter_anim_bufs.alloc(()));
        let b = AnimBufId(self.game.fighter_anim_bufs.alloc(()));
        let fp = &mut self.game.fighters[f.0];
        fp.x59C = Some(a);
        fp.x5A0 = Some(b);
        fp.x5A4 = 0;
        fp.x5A8 = 0;
        let kind = fp.kind;
        fp.x58C = kind_tables(kind).anim_count;
        if let Some((name, aram)) = self.game.load_anim_file(kind) {
            self.disc_load(name, aram);
        }
    }

    /// A fighter file's synchronous disc load (`lbFile_8001668C`), where the original loads
    /// it, on the audio timeline that times it: `dest` its ARAM address, or [`MAIN_MEMORY`]
    /// for main memory, whose heap isn't modeled. Nothing without a timeline (a state
    /// imported from a single call).
    pub fn disc_load(&mut self, name: &str, dest: u32) {
        if self.game.audio.clock.is_none() {
            return;
        }
        let (entrynum, len) = self.game.ft.data.files.entry(name);
        self.game.audio.load_file(self.data, entrynum, dest, len);
    }
}

impl Game {
    /// Puts a kind's animation file in ARAM unless it's there, `ftData_80085A14`: the
    /// address the frontend loaded it at. The original writes each animation's address into
    /// the kind's animation table, which `Running::anim_aram` works out from the file's.
    #[doc(alias = "ftData_80085A14")]
    pub fn load_anim_file(&mut self, kind: i32) -> Option<(&'static str, u32)> {
        let k = kind as usize;
        self.ft.anim_files.resize(KIND_COUNT, None);
        if self.ft.anim_files[k].is_some() {
            return None;
        }
        let name = kind_tables(kind)
            .anim_file
            .expect("a fighter kind without animations");
        let file = self.ft.data.files.anim_file(name).clone();
        let aram = file.aram;
        self.ft.anim_files[k] = Some(file);
        Some((name, aram))
    }
}

/// A figatree's frame count, `lbAnim_8001E8F8`.
#[doc(alias = "lbAnim_8001E8F8")]
pub fn figatree_frames(data: &Archives, tree: Option<DataRef>) -> f32 {
    tree.map_or(0.0, |t| data.f32(t.at(8)))
}
