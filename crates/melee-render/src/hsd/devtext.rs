/// `DrawASCII`'s constants: `@134`, `@133`, `@135` (doubles) and `@136` (a single).
const DOT_X: f64 = 0.3;
const DOT_Y: f64 = 0.9;
const COLON_Y: f64 = 0.7;
const STROKE: f32 = 0.11;

impl Ctx<'_> {
    /// A debug text screen's draw (`Draw::Text`).
    pub fn devtext(&mut self, d: &Draw) {
        match *d {
            Draw::TextScale { x, y, line_width } => self.text_scale(x, y, line_width),
            Draw::Rect { x, y, w, h, color } => self.text_rect(x, y, w, h, color),
            Draw::Ascii { chr, x, y, color } => self.text_ascii(chr, x, y, color),
            // The camera and the fog are the display pass's own draws.
            Draw::NoFog | Draw::Camera(_) => unreachable!("a screen's camera or fog as text"),
        }
    }

    /// `hsd_80391A04`: the glyphs' scale and line width (`lbl_804D6070` to `6078`), and the
    /// debug drawings' setup with them.
    #[doc(alias = "hsd_80391A04")]
    fn text_scale(&mut self, x: f64, y: f64, line_width: i32) {
        self.hsd.text_scale = (fp::frsp(x), fp::frsp(y));
        self.debug_draw_setup_width(line_width as u8);
    }

    /// `DrawRectangle`: a flat quad from (`x`, `y`), `w` by `h`, its corners clockwise.
    #[doc(alias = "DrawRectangle")]
    fn text_rect(&mut self, x: f64, y: f64, w: f64, h: f64, [r, g, b, a]: [u8; 4]) {
        self.gx.begin(GX_QUADS, GX_VTXFMT0, 4);
        let (x1, y1) = (fp::fadds(x, w), fp::fadds(y, h));
        for (px, py) in [(x, y), (x1, y), (x1, y1), (x, y1)] {
            self.gx.position2f32(px as f32, py as f32);
            self.gx.color4u8(r, g, b, a);
        }
        self.gx.end();
    }

    /// `DrawASCII`: a character's glyph at (`x`, `y`): its lines, or the points of `.` and `:`.
    #[doc(alias = "DrawASCII")]
    fn text_ascii(&mut self, chr: i32, x: f64, y: f64, [r, g, b, a]: [u8; 4]) {
        let (sx, sy) = self.hsd.text_scale;
        let point = |gx: &mut crate::gx::Gx, px: f64, py: f64| {
            gx.position2f32(fp::frsp(px) as f32, fp::frsp(py) as f32);
            gx.color4u8(r, g, b, a);
        };
        let index = match chr {
            0x30..=0x39 => chr - 0x30,
            0x41..=0x5A => chr - 0x41 + 10,
            0x61..=0x7A => chr - 0x61 + 10,
            0x2E => {
                self.gx.begin(GX_POINTS, GX_VTXFMT0, 1);
                point(self.gx, fp::fmadd(DOT_X, sx, x), fp::fmadd(DOT_Y, sy, y));
                self.gx.end();
                return;
            }
            0x3A => {
                self.gx.begin(GX_POINTS, GX_VTXFMT0, 2);
                let px = fp::fmadd(DOT_X, sx, x);
                point(self.gx, px, fp::fmadd(DOT_X, sy, y));
                point(self.gx, px, fp::fmadd(COLON_Y, sy, y));
                self.gx.end();
                return;
            }
            0x2D => 0x24,
            0x5F => 0x25,
            0x7E => 0x26,
            0x3E => 0x27,
            0x2F => 0x28,
            0x28 => 0x29,
            0x29 => 0x2A,
            0x2C => 0x2B,
            0x3C => 0x2C,
            0x2B => 0x2D,
            0x24 => 0x2E,
            _ => return,
        } as usize;
        let glyph = &FONT[index * 13..];
        let stroke = fp::lfs(STROKE.to_bits());
        let end = |n: u8, s: f64, o: f64| fp::fmadds(s, fp::fmuls(stroke, f64::from(n)), o) as f32;
        let mut i = 0;
        while i < 0x29 && glyph[i] != 0xFF {
            let (p0, p1) = (glyph[i], glyph[i + 1]);
            i += 2;
            self.gx.begin(GX_LINES, GX_VTXFMT0, 2);
            for p in [p0, p1] {
                self.gx
                    .position2f32(end(p >> 4, sx, x), end(p & 0xF, sy, y));
                self.gx.color4u8(r, g, b, a);
            }
            self.gx.end();
        }
    }
}
