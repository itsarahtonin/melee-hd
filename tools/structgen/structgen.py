#!/usr/bin/env python3
"""Generates melee-sim's mirrors of the game's structs from the decomp's type layouts.

Each C struct becomes a plain-data Rust struct with one field per C field: integers and
floats keep their width, arrays become arrays, nested structs nest, bitfields become their own
fields, and unions become big-endian byte arrays (state code often writes one member and reads
another, which a byte array reproduces exactly). The fields of an item's variables
(`config.TRACKED`, and the structs nested in them) are `it::Var`s, which know whether a new item
has written them yet. Pointers become the handle the config maps
their pointee to (`config.py`); function pointers become `CodeRef`, the original function's
address, which the game dispatches on. C types melee-sim already has (vectors, quaternions)
use its types.

Alongside, it generates each struct's `Mirror` implementation, which the oracle uses: import a
struct from ssbm-rs's memory (a capture, or a trace region) into the mirror, and compare a
mirror with memory field by field. Pointer fields go through the caller's `Cx`, which knows
how ssbm-rs's addresses relate to melee-sim's handles.

Usage: structgen.py TYPES_JSON OUT_DIR
  TYPES_JSON is ssbm-rs's typegen output (local/typegen/types.json in an ssbm-rs checkout).
  Writes OUT_DIR/structs.rs and OUT_DIR/mirror_gen.rs.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import config  # noqa: E402

INT = {(1, True): "i8", (1, False): "u8", (2, True): "i16", (2, False): "u16", (4, True): "i32", (4, False): "u32", (8, True): "i64", (8, False): "u64"}
FLOAT = {4: "f32", 8: "f64"}
RUST_KEYWORDS = {"type", "match", "ref", "move", "fn", "mod", "use", "loop", "box", "self", "super", "crate", "where", "impl", "trait", "struct", "enum", "const", "static", "mut", "pub", "in", "as", "dyn", "let", "if", "else", "for", "while", "return", "break", "continue", "true", "false", "unsafe", "extern", "async", "await", "yield", "macro", "priv", "abstract", "final", "override", "virtual", "become", "do", "typeof", "unsized", "try"}
HEADER = [
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "// Generated by tools/structgen from the decomp's type layouts. Do not edit; change",
    "// tools/structgen/config.py and regenerate.",
]


def rec_name(rid):
    """The C name of a record id like c:@S@Fighter, or a synthesized one for anonymous records."""
    m = re.match(r"c:@(?:S|U|SA|UA)@(.+)$", rid)
    if m:
        return m.group(1)
    return "Anon_" + re.sub(r"[^A-Za-z0-9]", "_", rid)


def rust_type_name(rid):
    return config.RENAME_TYPES.get(rec_name(rid), rec_name(rid))


def field_name(name):
    n = config.RENAME_FIELDS.get(name, name)
    return f"r#{n}" if n in RUST_KEYWORDS else n


def bit_type(bits):
    return "bool" if bits == 1 else "u32" if bits > 16 else "u16" if bits > 8 else "u8"


class Gen:
    def __init__(self, types):
        self.recs = types["records"]
        self.done = set()
        self.order = []
        self.current = None
        # The tracked structs (`config.TRACKED` and the structs nested in them), and the
        # records that use each record, to check a nested one isn't used elsewhere.
        self.tracked = set()
        self.users = {}

    def is_tracked(self, rid):
        return rid in self.tracked

    def external(self, t):
        return t["k"] == "rec" and rec_name(t["id"]) in config.EXTERNAL

    def pointer(self, to):
        """The handle type for a pointer to `to`, and its kind for the mirror."""
        if to["k"] == "fn":
            return "Option<CodeRef>", "code"
        if to["k"] == "rec":
            name = rec_name(to["id"])
            if name in config.POINTERS:
                return config.POINTERS[name], "handle"
            if name in config.DATA_TYPES:
                return "Option<DataRef>", "data"
        return config.DEFAULT_POINTER, "raw"

    def size(self, t):
        k = t["k"]
        if k in ("int", "float", "enum"):
            return t["size"]
        if k == "ptr":
            return 4
        if k == "arr":
            return t["n"] * self.size(t["of"])
        if k == "rec":
            return self.recs[t["id"]]["size"]
        raise ValueError(f"no size for {t}")

    def ty(self, t):
        k = t["k"]
        if k == "int":
            return INT[(t["size"], t["signed"])]
        if k == "float":
            return FLOAT[t["size"]]
        if k == "enum":
            return INT[(t["size"], True)]
        if k == "arr":
            return f"[{self.ty(t['of'])}; {t['n']}]"
        if k == "ptr":
            return self.pointer(t["to"])[0]
        if k == "rec":
            if self.external(t):
                return config.EXTERNAL[rec_name(t["id"])]
            r = self.recs[t["id"]]
            if r["kind"] == "union":
                return f"[u8; {r['size']}]"
            self.want(t["id"], self.current)
            return rust_type_name(t["id"])
        if k == "void":
            return "()"
        raise ValueError(f"no Rust type for {t}")

    def want(self, rid, user=None):
        self.users.setdefault(rid, set()).add(user)
        if user in self.tracked or rec_name(rid) in config.TRACKED:
            self.tracked.add(rid)
        if rid in self.done:
            return
        self.done.add(rid)
        saved = self.current
        self.current = rid
        for f in self.fields(rid):
            if "splice" not in f:
                self.ty(f["type"])
        self.current = saved
        self.order.append(rid)

    def check_tracked(self):
        for rid in self.tracked:
            if rec_name(rid) not in config.TRACKED:
                others = self.users[rid] - self.tracked
                assert not others, f"{rec_name(rid)} is nested in a tracked struct and used elsewhere"

    def fields(self, rid):
        """A record's fields, with any run config.SPLICE names replaced by one field of the
        hand-written type it gives."""
        r = self.recs[rid]
        splices = config.SPLICE.get(rec_name(rid), [])
        if isinstance(splices, tuple):
            splices = [splices]
        out = []
        done = set()
        unused = config.UNUSED.get(rec_name(rid), set())
        for f in r["fields"]:
            if f["name"] in unused:
                continue
            off = f["offset_bits"] // 8
            splice = next((sp for sp in splices if sp[1] <= off < sp[2]), None)
            if splice:
                if off == splice[1] and f["offset_bits"] % 8 == 0 and splice[0] not in done:
                    done.add(splice[0])
                    out.append({"name": splice[0], "offset_bits": off * 8, "splice": splice[3]})
                continue
            out.append(f)
        return out

    def struct(self, rid):
        r = self.recs[rid]
        name = rust_type_name(rid)
        out = [f"/// `{rec_name(rid)}`, {r['size']:#x} bytes."]
        # CloneFrom: a restore copies field by field, reusing the target's storage.
        out.append("#[derive(melee_derive::CloneFrom, Debug, PartialEq, melee_derive::StateEq)]")
        out.append(f"pub struct {name} {{")
        for f in self.fields(rid):
            off = f["offset_bits"] // 8
            bits = f" (bits {f['offset_bits'] % 8}..+{f['bits']})" if "bits" in f else ""
            if "splice" in f:
                # In a tracked struct the spliced type is one tracked field.
                t = f"Var<{f['splice']}>" if self.is_tracked(rid) else f["splice"]
            elif self.is_tracked(rid):
                t = self.tracked_ty(rid, f)
            else:
                t = bit_type(f["bits"]) if "bits" in f else self.handle_array(rid, f) or self.field_override(rid, f) or self.ty(f["type"])
            out.append(f"    /// +{off:#x}{bits}")
            out.append(f"    pub {field_name(f['name'])}: {t},")
        out.append("}")
        out.append("")
        out.append(f"impl Default for {name} {{")
        out.append("    fn default() -> Self {")
        out.append(f"        {name} {{")
        for f in self.fields(rid):
            if "splice" in f:
                d = "Var::new(Default::default())" if self.is_tracked(rid) else "Default::default()"
            elif self.is_tracked(rid):
                d = self.tracked_default(rid, f)
            else:
                ha = self.handle_array(rid, f)
                d = f"[None; {f['type']['n']}]" if ha else "None" if self.field_override(rid, f) else self.default(f)
            out.append(f"            {field_name(f['name'])}: {d},")
        out.append("        }")
        out.append("    }")
        out.append("}")
        if self.is_tracked(rid):
            out.append("")
            out.append(f"impl {name} {{")
            out.append("    /// Marks every field stale, as a new item finds its variables.")
            out.append("    pub fn mark_stale(&mut self) {")
            for f in self.fields(rid):
                fname = field_name(f["name"])
                t = f.get("type", {"k": "splice"})
                if "bits" not in f and t["k"] == "arr":
                    assert t["of"]["k"] != "arr", f"a nested array in tracked {name}"
                    out.append(f"        self.{fname}.iter_mut().for_each(|v| v.mark_stale());")
                else:
                    out.append(f"        self.{fname}.mark_stale();")
            out.append("    }")
            out.append("}")
        return "\n".join(out)

    # A tracked struct's fields: each value an `it::Var`, element by element in arrays; nested
    # structs are tracked themselves.

    def nested(self, t):
        """Whether `t` is a struct a tracked field holds as a tracked struct of its own."""
        return t["k"] == "rec" and not self.external(t) and self.recs[t["id"]]["kind"] != "union"

    def tracked_ty(self, rid, f):
        if "bits" in f:
            return f"Var<{bit_type(f['bits'])}>"
        key = f"{rec_name(rid)}.{f['name']}"
        if self.handle_array(rid, f):
            return f"[Var<Option<{config.FIELD_HANDLE_ARRAYS[key]}>>; {f['type']['n']}]"
        over = self.field_override(rid, f)
        if over:
            return f"Var<{over}>"
        return self.wrap_ty(f["type"])

    def wrap_ty(self, t):
        if t["k"] == "arr":
            return f"[{self.wrap_ty(t['of'])}; {t['n']}]"
        if self.nested(t):
            return self.ty(t)
        return f"Var<{self.ty(t)}>"

    def tracked_default(self, rid, f):
        if "bits" in f or self.field_override(rid, f):
            return "Var::new(Default::default())"
        if self.handle_array(rid, f):
            return "core::array::from_fn(|_| Var::new(None))"
        return self.wrap_default(f["type"])

    def wrap_default(self, t):
        if t["k"] == "arr":
            return f"core::array::from_fn(|_| {self.wrap_default(t['of'])})"
        if self.nested(t):
            return "Default::default()"
        return "Var::new(Default::default())"

    def wrap_import(self, t, at, depth=0):
        if t["k"] == "arr":
            es = self.size(t["of"])
            i = f"i{depth}"
            inner = self.wrap_import(t["of"], f"{at} + {i} as u32 * {es:#x}", depth + 1)
            return f"core::array::from_fn(|{i}| {inner})"
        if self.nested(t):
            return self.import_expr(t, at, depth)
        return f"Var::new({self.import_expr(t, at, depth)})"

    def wrap_compare(self, t, ours, at, path, depth=0):
        """Statements comparing a tracked field's `ours` with memory: a stale value is left out."""
        if t["k"] == "arr":
            es = self.size(t["of"])
            i = f"i{depth}"
            inner = self.wrap_compare(t["of"], f"{ours}[{i}]", f"{at} + {i} as u32 * {es:#x}", f"format!(\"{{}}[{{}}]\", {path}, {i})", depth + 1)
            return [f"for {i} in 0..{t['n']} {{"] + ["    " + s for s in inner] + ["}"]
        if self.nested(t) or (t["k"] == "rec" and self.ty(t) == "Vec3"):
            # A nested tracked struct, or a vector, which compares its live components.
            return [f"{ours}.compare(m, {at}, &{path}, cx);"]
        inner = self.compare_stmts(t, f"(*{ours}.peek())", at, path, depth)
        return [f"if {ours}.live(&{path}, cx) {{"] + ["    " + s for s in inner] + ["}"]

    def handle_array(self, rid, f):
        """The type config.FIELD_HANDLE_ARRAYS gives this array of words, if any."""
        h = config.FIELD_HANDLE_ARRAYS.get(f"{rec_name(rid)}.{f['name']}")
        if h is None:
            return None
        t = f["type"]
        assert t["k"] == "arr" and t["of"]["k"] == "int" and t["of"]["size"] == 4, f"{rec_name(rid)}.{f['name']} isn't an array of words"
        return f"[Option<{h}>; {t['n']}]"

    def field_override(self, rid, f):
        """The type config.FIELD_POINTERS or config.FIELD_DATA gives this pointer field, if any."""
        key = f"{rec_name(rid)}.{f['name']}"
        if key in config.FIELD_DATA:
            return "Option<DataRef>"
        return config.FIELD_POINTERS.get(key)

    def default(self, f):
        if "bits" in f:
            return "false" if f["bits"] == 1 else "0"
        return self.default_of(f["type"])

    def default_of(self, t):
        k = t["k"]
        if k in ("int", "enum"):
            return "0"
        if k == "float":
            return "0.0"
        if k == "ptr":
            return "None" if self.pointer(t["to"])[0].startswith("Option<") else "Default::default()"
        if k == "arr":
            inner = self.default_of(t["of"])
            return f"[{inner}; {t['n']}]" if inner in ("0", "0.0", "None") else f"core::array::from_fn(|_| {inner})"
        if k == "rec":
            r = self.recs[t["id"]]
            if r["kind"] == "union" and not self.external(t):
                return f"[0; {r['size']}]"
            return "Default::default()"
        return "Default::default()"

    # The mirror: import from memory and compare with it.

    def import_expr(self, t, at, depth=0):
        """An expression reading a value of type `t` at address expression `at`."""
        k = t["k"]
        if k in ("int", "enum"):
            size = t["size"]
            signed = t.get("signed", True) if k == "int" else True
            raw = {1: f"m.u8({at})", 2: f"m.u16({at})", 4: f"m.u32({at})", 8: f"m.u64({at})"}[size]
            return f"{raw} as {INT[(size, signed)]}" if signed else raw
        if k == "float":
            return f"f32::from_bits(m.u32({at}))" if t["size"] == 4 else f"f64::from_bits(m.u64({at}))"
        if k == "ptr":
            ty, kind = self.pointer(t["to"])
            if kind == "code":
                return f"code(m.u32({at}))"
            if kind == "data":
                return f"cx.import_data(m.u32({at}))"
            if kind == "raw":
                return f"RawPtr(m.u32({at}))"
            handle = ty[len("Option<"):-1]
            return f'cx.import_handle("{handle}", m.u32({at})).map({handle})'
        if k == "arr":
            es = self.size(t["of"])
            i = f"i{depth}"
            inner = self.import_expr(t["of"], f"{at} + {i} as u32 * {es:#x}", depth + 1)
            return f"core::array::from_fn(|{i}| {inner})"
        if k == "rec":
            r = self.recs[t["id"]]
            if r["kind"] == "union" and not self.external(t):
                return f"m.bytes({at})"
            return f"{self.ty(t)}::import(m, {at}, cx)"
        raise ValueError(f"no import for {t}")

    def compare_stmts(self, t, ours, at, path, depth=0):
        """Statements comparing `ours` (an expression) with memory at `at`."""
        k = t["k"]
        if k in ("int", "enum"):
            theirs = self.import_expr(t, at)
            return [f"if {ours} != {theirs} {{ cx.mismatch(&{path}, format!(\"{{:?}}\", {ours}), format!(\"{{:?}}\", {theirs})); }}"]
        if k == "float":
            bits = f"m.u32({at})" if t["size"] == 4 else f"m.u64({at})"
            return [f"if {ours}.to_bits() != {bits} {{ cx.mismatch(&{path}, format!(\"{{:?}}\", {ours}), format!(\"{{:?}}\", {self.import_expr(t, at)})); }}"]
        if k == "ptr":
            ty, kind = self.pointer(t["to"])
            if kind == "code":
                return [f"if {ours}.map_or(0, |c| c.0) != m.u32({at}) {{ cx.mismatch(&{path}, format!(\"{{:?}}\", {ours}), format!(\"{{:#x}}\", m.u32({at}))); }}"]
            if kind == "data":
                return [f"cx.compare_data(&{path}, {ours}, m.u32({at}));"]
            if kind == "raw":
                return [f"if {ours}.0 != m.u32({at}) {{ cx.mismatch(&{path}, format!(\"{{:#x}}\", {ours}.0), format!(\"{{:#x}}\", m.u32({at}))); }}"]
            handle = ty[len("Option<"):-1]
            return [f'cx.compare_handle(&{path}, "{handle}", {ours}.map(|h| h.0), m.u32({at}));']
        if k == "arr":
            es = self.size(t["of"])
            i = f"i{depth}"
            inner = self.compare_stmts(t["of"], f"{ours}[{i}]", f"{at} + {i} as u32 * {es:#x}", f"format!(\"{{}}[{{}}]\", {path}, {i})", depth + 1)
            return [f"for {i} in 0..{t['n']} {{"] + ["    " + s for s in inner] + ["}"]
        if k == "rec":
            r = self.recs[t["id"]]
            if r["kind"] == "union" and not self.external(t):
                n = r["size"]
                return [f"if {ours} != m.bytes::<{n}>({at}) {{ cx.mismatch(&{path}, format!(\"{{:02x?}}\", {ours}), format!(\"{{:02x?}}\", m.bytes::<{n}>({at}))); }}"]
            return [f"{ours}.compare(m, {at}, &{path}, cx);"]
        raise ValueError(f"no compare for {t}")

    def mirror(self, rid):
        r = self.recs[rid]
        name = rust_type_name(rid)
        imp = []
        cmp = []
        tracked = self.is_tracked(rid)
        for f in self.fields(rid):
            fname = field_name(f["name"])
            off = f["offset_bits"] // 8
            at = f"at + {off:#x}"
            path = f"format!(\"{{path}}.{f['name']}\")"
            if tracked:
                self.tracked_mirror(rid, f, fname, at, path, imp, cmp)
                continue
            if "splice" in f:
                imp.append(f"            {fname}: {f['splice']}::import(m, {at}, cx),")
                cmp.append(f"        self.{fname}.compare(m, {at}, &{path}, cx);")
                continue
            if "bits" in f:
                bt = bit_type(f["bits"])
                read = f"m.bits(at, {f['offset_bits']}, {f['bits']})"
                imp.append(f"            {fname}: {read} != 0," if bt == "bool" else f"            {fname}: {read} as {bt},")
                ours = f"(self.{fname} as u32)"
                cmp.append(f"        if {ours} != {read} {{ cx.mismatch(&{path}, format!(\"{{:?}}\", self.{fname}), format!(\"{{:?}}\", {read})); }}")
                continue
            if self.handle_array(rid, f):
                h = config.FIELD_HANDLE_ARRAYS[f"{rec_name(rid)}.{f['name']}"]
                n = f["type"]["n"]
                imp.append(f'            {fname}: core::array::from_fn(|i| cx.import_handle("{h}", m.u32({at} + 4 * i as u32)).map({h})),')
                cmp.append(f"        for i in 0..{n} {{")
                cmp.append(f'            cx.compare_handle(&format!("{{path}}.{f["name"]}[{{i}}]"), "{h}", self.{fname}[i].map(|h| h.0), m.u32({at} + 4 * i as u32));')
                cmp.append("        }")
                continue
            over = self.field_override(rid, f)
            if over:
                assert f["type"]["k"] == "ptr", f"{rec_name(rid)}.{f['name']} isn't a pointer"
                if over == "Option<DataRef>":
                    imp.append(f"            {fname}: cx.import_data(m.u32({at})),")
                    cmp.append(f"        cx.compare_data(&{path}, self.{fname}, m.u32({at}));")
                    continue
                handle = over[len("Option<"):-1]
                imp.append(f'            {fname}: cx.import_handle("{handle}", m.u32({at})).map({handle}),')
                cmp.append(f'        cx.compare_handle(&{path}, "{handle}", self.{fname}.map(|h| h.0), m.u32({at}));')
                continue
            imp.append(f"            {fname}: {self.import_expr(f['type'], at)},")
            for s in self.compare_stmts(f["type"], f"self.{fname}", at, path):
                cmp.append("        " + s)
        out = [f"impl Mirror for {name} {{"]
        out.append(f"    const SIZE: u32 = {r['size']:#x};")
        out.append("")
        out.append("    fn import(m: &Mem, at: u32, cx: &mut dyn Cx) -> Self {")
        out.append("        let _ = (&m, at, &cx);")
        out.append(f"        {name} {{")
        out.extend(imp)
        out.append("        }")
        out.append("    }")
        out.append("")
        out.append("    fn compare(&self, m: &Mem, at: u32, path: &str, cx: &mut dyn Cx) {")
        out.append("        let _ = (&m, at, path, &cx);")
        out.extend(cmp)
        out.append("    }")
        out.append("}")
        return "\n".join(out)

    # The exporter: plain structs (no pointers) written back to memory's bytes, for the ones
    # config.EXPORT_ROOTS reaches.

    def export_reach(self, rid, out):
        if rid in out:
            return
        out.add(rid)
        for f in self.fields(rid):
            assert "splice" not in f, f"{rec_name(rid)}.{f['name']}: a splice in an exported struct"
            t = f["type"]
            while t["k"] == "arr":
                t = t["of"]
            assert t["k"] != "ptr", f"{rec_name(rid)}.{f['name']}: a pointer in an exported struct"
            if t["k"] == "rec" and not (self.recs[t["id"]]["kind"] == "union" and not self.external(t)):
                self.export_reach(t["id"], out)

    def export_stmts(self, t, ours, at, depth=0):
        """Statements writing `ours` of type `t` at address expression `at`."""
        k = t["k"]
        if k in ("int", "enum"):
            size = t["size"]
            ty = {1: "u8", 2: "u16", 4: "u32", 8: "u64"}[size]
            return [f"m.put_{ty}({at}, {ours} as {ty});"]
        if k == "float":
            return [f"m.put_u32({at}, {ours}.to_bits());"] if t["size"] == 4 else [f"m.put_u64({at}, {ours}.to_bits());"]
        if k == "arr":
            es = self.size(t["of"])
            i = f"i{depth}"
            inner = self.export_stmts(t["of"], f"{ours}[{i}]", f"{at} + {i} as u32 * {es:#x}", depth + 1)
            return [f"for {i} in 0..{t['n']} {{"] + ["    " + s for s in inner] + ["}"]
        if k == "rec":
            r = self.recs[t["id"]]
            if r["kind"] == "union" and not self.external(t):
                return [f"m.put_bytes({at}, &{ours});"]
            return [f"{ours}.export(m, {at});"]
        raise ValueError(f"no export for {t}")

    def exporter(self, rid):
        name = rust_type_name(rid)
        out = [f"impl Export for {name} {{", "    fn export(&self, m: &mut MemMut, at: u32) {", "        let _ = (&m, at);"]
        for f in self.fields(rid):
            fname = field_name(f["name"])
            off = f["offset_bits"] // 8
            if "bits" in f:
                out.append(f"        m.put_bits(at, {f['offset_bits']}, {f['bits']}, self.{fname} as u32);")
                continue
            for st in self.export_stmts(f["type"], f"self.{fname}", f"at + {off:#x}"):
                out.append("        " + st)
        out.append("    }")
        out.append("}")
        return "\n".join(out)

    # The image's layouts: every struct config.LAY_ROOTS reaches (a fighter's, an item's),
    # written back as the game keeps it when its block goes back to the heap. Pointers become
    # the addresses the caller's `LayCx` gives; a stale variable stays unknown.

    def lay_reach(self, rid, out, splices):
        if rid in out:
            return
        out.add(rid)
        for f in self.fields(rid):
            if "splice" in f:
                splices.add(f["splice"])
                continue
            if "bits" in f:
                continue
            t = f["type"]
            while t["k"] == "arr":
                t = t["of"]
            if t["k"] == "rec":
                if self.external(t):
                    splices.add(config.EXTERNAL[rec_name(t["id"])])
                elif self.recs[t["id"]]["kind"] != "union":
                    self.lay_reach(t["id"], out, splices)

    def lay_stmts(self, t, ours, at, depth=0):
        """Statements laying `ours` of type `t` out at address expression `at`."""
        k = t["k"]
        if k in ("int", "enum"):
            ty = {1: "u8", 2: "u16", 4: "u32", 8: "u64"}[t["size"]]
            return [f"l.put_{ty}({at}, {ours} as {ty});"]
        if k == "float":
            return [f"l.put_u32({at}, {ours}.to_bits());"] if t["size"] == 4 else [f"l.put_u64({at}, {ours}.to_bits());"]
        if k == "ptr":
            ty, kind = self.pointer(t["to"])
            if kind == "code":
                return [f"l.put_u32({at}, {ours}.map_or(0, |c| c.0));"]
            if kind == "data":
                return [f"l.put_word({at}, cx.data({ours}));"]
            if kind == "raw":
                return [f"l.put_u32({at}, {ours}.0);"]
            handle = ty[len("Option<"):-1]
            return [f'l.put_word({at}, cx.handle("{handle}", {ours}.map(|h| h.0)));']
        if k == "arr":
            es = self.size(t["of"])
            i = f"i{depth}"
            inner = self.lay_stmts(t["of"], f"{ours}[{i}]", f"{at} + {i} as u32 * {es:#x}", depth + 1)
            return [f"for {i} in 0..{t['n']} {{"] + ["    " + s for s in inner] + ["}"]
        if k == "rec":
            r = self.recs[t["id"]]
            if r["kind"] == "union" and not self.external(t):
                return [f"l.put_bytes({at}, &{ours});"]
            return [f"{ours}.lay(l, {at}, cx);"]
        raise ValueError(f"no layout for {t}")

    def wrap_lay(self, t, ours, at, depth=0):
        """A tracked field's layout: a stale value stays unknown."""
        if t["k"] == "arr":
            es = self.size(t["of"])
            i = f"i{depth}"
            inner = self.wrap_lay(t["of"], f"{ours}[{i}]", f"{at} + {i} as u32 * {es:#x}", depth + 1)
            return [f"for {i} in 0..{t['n']} {{"] + ["    " + s for s in inner] + ["}"]
        if self.nested(t) or (t["k"] == "rec" and self.ty(t) == "Vec3"):
            return [f"{ours}.lay(l, {at}, cx);"]
        inner = self.lay_stmts(t, f"(*{ours}.peek())", at, depth)
        return [f"if {ours}.is_live() {{"] + ["    " + s for s in inner] + ["}"]

    def layout(self, rid):
        name = rust_type_name(rid)
        tracked = self.is_tracked(rid)
        out = [f"impl LayOut for {name} {{", "    fn lay(&self, l: &mut Lay, at: u32, cx: &dyn LayCx) {", "        let _ = (&l, at, &cx);"]
        for f in self.fields(rid):
            fname = field_name(f["name"])
            off = f["offset_bits"] // 8
            at = f"at + {off:#x}"
            ours = f"self.{fname}"
            stmts = []
            if "splice" in f:
                stmts = [f"{ours}.peek().lay(l, {at}, cx);"] if tracked else [f"{ours}.lay(l, {at}, cx);"]
                if tracked:
                    stmts = [f"if {ours}.is_live() {{", "    " + stmts[0], "}"]
            elif "bits" in f:
                v = f"*{ours}.peek()" if tracked else ours
                stmts = [f"l.put_bits(at, {f['offset_bits']}, {f['bits']}, ({v}) as u32);"]
                if tracked:
                    stmts = [f"if {ours}.is_live() {{", "    " + stmts[0], "}"]
            elif self.handle_array(rid, f):
                h = config.FIELD_HANDLE_ARRAYS[f"{rec_name(rid)}.{f['name']}"]
                n = f["type"]["n"]
                v = f"{ours}[i].peek()" if tracked else f"{ours}[i]"
                stmts = [f"for i in 0..{n} {{"]
                if tracked:
                    stmts.append(f"    if {ours}[i].is_live() {{")
                    stmts.append(f'        l.put_word({at} + 4 * i as u32, cx.handle("{h}", {v}.map(|h| h.0)));')
                    stmts.append("    }")
                else:
                    stmts.append(f'    l.put_word({at} + 4 * i as u32, cx.handle("{h}", {v}.map(|h| h.0)));')
                stmts.append("}")
            elif self.field_override(rid, f):
                over = self.field_override(rid, f)
                v = f"*{ours}.peek()" if tracked else ours
                if over == "Option<DataRef>":
                    st = f"l.put_word({at}, cx.data({v}));"
                else:
                    handle = over[len("Option<"):-1]
                    st = f'l.put_word({at}, cx.handle("{handle}", ({v}).map(|h| h.0)));'
                stmts = [f"if {ours}.is_live() {{", "    " + st, "}"] if tracked else [st]
            elif tracked:
                stmts = self.wrap_lay(f["type"], ours, at)
            else:
                stmts = self.lay_stmts(f["type"], ours, at)
            out.extend("        " + s for s in stmts)
        out.append("    }")
        out.append("}")
        return "\n".join(out)

    def tracked_mirror(self, rid, f, fname, at, path, imp, cmp):
        """A tracked struct's field's import and comparison."""
        def guarded(stmts):
            cmp.append(f"        if self.{fname}.live(&{path}, cx) {{")
            cmp.extend("            " + s for s in stmts)
            cmp.append("        }")
        if "splice" in f:
            imp.append(f"            {fname}: Var::new({f['splice']}::import(m, {at}, cx)),")
            guarded([f"self.{fname}.peek().compare(m, {at}, &{path}, cx);"])
            return
        if "bits" in f:
            bt = bit_type(f["bits"])
            read = f"m.bits(at, {f['offset_bits']}, {f['bits']})"
            imp.append(f"            {fname}: Var::new({read} != 0)," if bt == "bool" else f"            {fname}: Var::new({read} as {bt}),")
            guarded([f"if (*self.{fname}.peek() as u32) != {read} {{ cx.mismatch(&{path}, format!(\"{{:?}}\", self.{fname}.peek()), format!(\"{{:?}}\", {read})); }}"])
            return
        if self.handle_array(rid, f):
            h = config.FIELD_HANDLE_ARRAYS[f"{rec_name(rid)}.{f['name']}"]
            n = f["type"]["n"]
            imp.append(f'            {fname}: core::array::from_fn(|i| Var::new(cx.import_handle("{h}", m.u32({at} + 4 * i as u32)).map({h}))),')
            cmp.append(f"        for i in 0..{n} {{")
            cmp.append(f'            let p = format!("{{path}}.{f["name"]}[{{i}}]");')
            cmp.append(f"            if self.{fname}[i].live(&p, cx) {{")
            cmp.append(f'                cx.compare_handle(&p, "{h}", self.{fname}[i].peek().map(|h| h.0), m.u32({at} + 4 * i as u32));')
            cmp.append("            }")
            cmp.append("        }")
            return
        over = self.field_override(rid, f)
        if over:
            assert f["type"]["k"] == "ptr", f"{rec_name(rid)}.{f['name']} isn't a pointer"
            if over == "Option<DataRef>":
                imp.append(f"            {fname}: Var::new(cx.import_data(m.u32({at}))),")
                guarded([f"cx.compare_data(&{path}, *self.{fname}.peek(), m.u32({at}));"])
                return
            handle = over[len("Option<"):-1]
            imp.append(f'            {fname}: Var::new(cx.import_handle("{handle}", m.u32({at})).map({handle})),')
            guarded([f'cx.compare_handle(&{path}, "{handle}", self.{fname}.peek().map(|h| h.0), m.u32({at}));'])
            return
        imp.append(f"            {fname}: {self.wrap_import(f['type'], at)},")
        for st in self.wrap_compare(f["type"], f"self.{fname}", at, path):
            cmp.append("        " + st)


def main():
    types = json.load(open(sys.argv[1], encoding="utf-8"))
    out_dir = Path(sys.argv[2])
    g = Gen(types)
    by_name = {rec_name(rid): rid for rid in types["records"]}
    for root in config.ROOTS:
        g.want(by_name[root])
    g.check_tracked()
    structs = HEADER + [
        "#![allow(non_snake_case, non_camel_case_types, unused_imports, clippy::all)]",
        "",
        config.PRELUDE,
        "",
    ]
    for rid in g.order:
        structs.append(g.struct(rid))
        structs.append("")
    mirror = HEADER + [
        "#![allow(non_snake_case, unused_comparisons, unused_imports, unused_parens, clippy::all)]",
        "",
        "use super::handles::*;",
        "use super::mirror::{Cx, Export, LayCx, LayOut, Mem, MemMut, Mirror, code};",
        "use crate::hsd::export::Lay;",
        "use super::structs::*;",
        "use super::gr::GroundVars;",
        "use crate::hsd::dobj::DObjId;",
        "use crate::hsd::gobj::GObjId;",
        "use crate::hsd::jobj::JObjId;",
        "use crate::hsd::tobj::TObjId;",
        "use crate::mp::coll::{EcbSource, X34Flags, X35Flags};",
        *config.EXTRA_USES,
        "use crate::quat::Quat;",
        "use crate::vec::Vec3;",
        "use crate::game::it::Var;",
        "",
    ]
    for rid in g.order:
        mirror.append(g.mirror(rid))
        mirror.append("")
    exported = set()
    for root in config.EXPORT_ROOTS:
        g.export_reach(by_name[root], exported)
    for rid in g.order:
        if rid in exported:
            mirror.append(g.exporter(rid))
            mirror.append("")
    laid = set()
    lay_splices = set()
    for root in config.LAY_ROOTS:
        g.lay_reach(by_name[root], laid, lay_splices)
    for rid in g.order:
        if rid in laid:
            mirror.append(g.layout(rid))
            mirror.append("")
    print("hand-written layouts needed:", ", ".join(sorted(lay_splices)))
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "structs.rs").write_text("\n".join(structs), encoding="utf-8", newline="\n")
    (out_dir / "mirror_gen.rs").write_text("\n".join(mirror), encoding="utf-8", newline="\n")
    print(f"{len(g.order)} structs")


if __name__ == "__main__":
    main()
