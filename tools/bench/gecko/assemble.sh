#!/bin/bash
# Assembles the boot codes into src/gecko_words.rs: each code's instruction words, with the
# word where its match data starts. Needs powerpc-eabi-as and powerpc-eabi-objcopy (the decomp's
# build/binutils has them): BINUTILS=/c/Projects/melee/build/binutils bash tools/bench/gecko/assemble.sh
set -eu
here=$(cd "$(dirname "$0")" && pwd)
bin=${BINUTILS:-/c/Projects/melee/build/binutils}
tmp=$(mktemp -d)
out="$here/../src/gecko_words.rs"
{
    echo "// Generated by tools/bench/gecko/assemble.sh from the .s files beside it; do not edit."
    echo
    for name in scene info; do
        (cd "$here" && "$bin/powerpc-eabi-as" -mgekko -mregnames -o "$tmp/$name.o" "$name.s")
        "$bin/powerpc-eabi-objcopy" -O binary -j .text "$tmp/$name.o" "$tmp/$name.bin"
        data=$("$bin/powerpc-eabi-nm" "$tmp/$name.o" | awk '$3 == "match_data" { print $1 }')
        upper=$(echo "$name" | tr a-z A-Z)
        echo "/// \`$name.s\`."
        echo "pub const ${upper}: &[u32] = &["
        od -An -v -tx1 "$tmp/$name.bin" | tr -s ' \n' ' ' | sed 's/^ //' |
            awk '{ for (i = 1; i <= NF; i += 4) printf "    0x%s%s%s%s,\n", toupper($i), toupper($(i+1)), toupper($(i+2)), toupper($(i+3)) }'
        echo "];"
        echo "/// The word of \`${upper}\` where its match data starts (after \`match_data\`'s \`blrl\`)."
        echo "pub const ${upper}_DATA: usize = $(( (16#$data + 4) / 4 ));"
        echo
    done
} > "$out.tmp"
mv "$out.tmp" "$out"
rm -rf "$tmp"
echo "wrote $out"
