#!/usr/bin/env python3
"""Transcribes each character's file and callback tables from the executable into a Rust
table: its data file and the `ftData` symbol in it (`ftData_803C1F40`), its costumes' files and
symbols (`CostumeListsForeachCharacter`, `ftData_803C2360`), its animation file
(`ftData_803C23E4`) and how many animations it has (`ftData_Table_Unk0`), its effect file's
number (`ftData_UnkBytePerCharacter`), its action-state table (`ftData_CharacterStateTables`),
and the addresses of its callbacks the fighter code calls by kind.

Usage: fighter_files.py MAIN_DOL SYMBOLS_TXT OUT_RS
  MAIN_DOL is the disc's main.dol (the decomp extracts it to orig/GALE01/sys/main.dol);
  SYMBOLS_TXT is the decomp's config/GALE01/symbols.txt.
"""

import re
import struct
import sys

KINDS = 33

# Callback tables indexed by fighter kind: (symbol, Rust field).
CALLBACKS = [
    ('ftData_Table_Unk1', 'on_first_init'),
    ('ftData_OnLoad', 'on_load'),
    ('ftData_OnDeath', 'on_death'),
    ('ftKindCalcIndiviParamTable', 'load_special_attrs'),
]


def load_dol(path):
    b = open(path, 'rb').read()
    offs = struct.unpack('>18I', b[0:72])
    addrs = struct.unpack('>18I', b[72:144])
    sizes = struct.unpack('>18I', b[144:216])
    sections = [(a, o, s) for a, o, s in zip(addrs, offs, sizes) if s]

    def read(addr, n):
        for a, o, s in sections:
            if a <= addr and addr + n <= a + s:
                return b[o + addr - a:o + addr - a + n]
        raise ValueError(f'{addr:#x} not in the DOL')
    return read


def main():
    read = load_dol(sys.argv[1])
    syms = {}
    names = {}
    for line in open(sys.argv[2], encoding='utf-8'):
        m = re.match(r'(\S+) = \.(\w+):0x([0-9A-Fa-f]+); // type:(\w+)', line)
        if not m:
            continue
        name, _, addr, kind = m.groups()
        addr = int(addr, 16)
        syms[name] = addr
        if kind == 'function':
            names[addr] = name

    def word(a):
        return struct.unpack('>I', read(a, 4))[0]

    def string(a):
        if a == 0:
            return None
        out = b''
        while True:
            c = read(a, 1)
            if c == b'\0':
                return out.decode('ascii')
            out += c
            a += 1

    def opt_str(s):
        return 'None' if s is None else f'Some("{s}")'

    out = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by tools/tables/fighter_files.py from the executable. Do not edit.',
        '#![allow(clippy::all)]',
        '',
        'use super::data::{CostumeFiles, KindTables};',
        '',
        '/// Every fighter kind\'s tables, by kind.',
        f'pub static KINDS: [KindTables; {KINDS}] = [',
    ]
    for k in range(KINDS):
        dat = string(word(syms['ftData_803C1F40'] + 8 * k))
        sym = string(word(syms['ftData_803C1F40'] + 8 * k + 4))
        n = read(syms['CostumeListsForeachCharacter'] + 8 * k + 4, 1)[0]
        strings = word(syms['ftData_803C2360'] + 4 * k)
        costumes = []
        for c in range(n):
            if strings == 0:
                break
            e = strings + 12 * c
            costumes.append((string(word(e)), string(word(e + 4)), string(word(e + 8))))
        anim = string(word(syms['ftData_803C23E4'] + 4 * k))
        count = word(syms['ftData_Table_Unk0'] + 8 * k + 4)
        effect = read(syms['ftData_UnkBytePerCharacter'] + k, 1)[0]
        states = word(syms['ftData_CharacterStateTables'] + 4 * k)
        out.append(f'    // {k}: {dat}')
        out.append('    KindTables {')
        out.append(f'        dat_file: {opt_str(dat)},')
        out.append(f'        data_symbol: {opt_str(sym)},')
        out.append(f'        costume_count: {n},')
        out.append('        costumes: &[')
        for f, j, m in costumes:
            out.append(f'            CostumeFiles {{ file: {opt_str(f)}, joint: {opt_str(j)}, matanim: {opt_str(m)} }},')
        out.append('        ],')
        out.append(f'        anim_file: {opt_str(anim)},')
        out.append(f'        anim_count: {count},')
        out.append(f'        effect_file: {effect},')
        out.append(f'        state_table: {states:#x},')
        for table, field in CALLBACKS:
            f = word(syms[table] + 4 * k)
            name = names.get(f, '-') if f else '-'
            out.append(f'        // {name}')
            out.append(f'        {field}: {f:#x},')
        out.append('    },')
    out.append('];')
    open(sys.argv[3], 'w', newline='\n').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
