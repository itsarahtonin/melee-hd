#!/usr/bin/env python3
"""Copies regions of the executable's data the game points into as loaded data (the dummy
stage's defaults: its lights, `GroundParam` and `map_head`) into one archive in the DAT
format, each word that holds an address in the regions relocated, so melee-sim reads them
as it reads a disc file's data (`DataRef`) and the oracle maps their addresses back.

Usage: exe_data.py MAIN_DOL OUT_RS
  MAIN_DOL is the disc's main.dol (the decomp extracts it to orig/GALE01/sys/main.dol).
"""

import struct
import sys

# (address, length) of each region, in the order the archive's data holds them.
REGIONS = [
    # `Ground_803E065C` to `grDatFiles_803E0924`'s end: the default lights' descriptors and
    # list, the dummy stage's stage parameters, `GroundParam` and `map_head`.
    (0x803E065C, 0x803E0954 - 0x803E065C),
    # `Ground_804D4500` to `Ground_804D451C`'s end: the default lights' animation lists,
    # range and light lists.
    (0x804D4500, 0x804D4524 - 0x804D4500),
]


def load_dol(path):
    b = open(path, 'rb').read()
    offs = struct.unpack('>18I', b[0:72])
    addrs = struct.unpack('>18I', b[72:144])
    sizes = struct.unpack('>18I', b[144:216])
    sections = [(a, o, s) for a, o, s in zip(addrs, offs, sizes) if s]

    def read(addr, n):
        for a, o, s in sections:
            if a <= addr and addr + n <= a + s:
                return b[o + addr - a:o + addr - a + n]
        raise ValueError(f'{addr:#x} not in the DOL')
    return read


def main():
    read = load_dol(sys.argv[1])
    # A word of padding first: an address relocated to offset 0 would read as null.
    data = bytearray(4)
    places = []
    for addr, n in REGIONS:
        places.append((addr, len(data), n))
        data += read(addr, n)
        data += b'\0' * (-len(data) % 4)

    def offset_of(a):
        for addr, off, n in places:
            if addr <= a < addr + n:
                return off + a - addr
        return None
    relocs = []
    for i in range(0, len(data), 4):
        w = struct.unpack('>I', data[i:i + 4])[0]
        o = offset_of(w)
        if o is not None:
            data[i:i + 4] = struct.pack('>I', o)
            relocs.append(i)
    # A DAT file: the header, the data, the relocation table; no symbols.
    body = bytes(data) + b''.join(struct.pack('>I', r) for r in relocs)
    size = 0x20 + len(body)
    header = struct.pack('>5I', size, len(data), len(relocs), 0, 0) + b'\0' * 12
    file = header + body
    out = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by tools/tables/exe_data.py from the executable. Do not edit.',
        '',
        '//! Regions of the executable\'s data the game points into as loaded data, as one archive',
        '//! (a DAT file whose relocations are the regions\' addresses into themselves): the',
        '//! dummy stage\'s defaults.',
        '',
        '/// Each region: its address, its offset in the archive\'s data, its length.',
        f'pub const REGIONS: [(u32, u32, u32); {len(places)}] = [',
    ]
    for addr, off, n in places:
        out.append(f'    ({addr:#x}, {off:#x}, {n:#x}),')
    out.append('];')
    out.append('')
    out.append('/// The archive.')
    out.append(f'pub const FILE: [u8; {len(file)}] = [')
    for i in range(0, len(file), 16):
        out.append('    ' + ', '.join(f'0x{x:02X}' for x in file[i:i + 16]) + ',')
    out.append('];')
    out.append('')
    open(sys.argv[2], 'w', newline='\n', encoding='utf-8').write('\n'.join(out))
    print(f'{len(data):#x} bytes, {len(relocs)} pointers')


if __name__ == '__main__':
    main()
