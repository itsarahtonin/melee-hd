#!/usr/bin/env python3
"""Transcribes the per-character callback tables the common action states dispatch through
(`ftData_SpecialN` and the other `ftData_*` tables of 33 function pointers, one per fighter
kind) from the executable into a Rust table of each fighter kind's addresses, which the
character registry's entries hold (`ft::registry`) and the common code calls by address.

Usage: kind_callbacks.py MAIN_DOL SYMBOLS_TXT OUT_RS
  MAIN_DOL is the disc's main.dol (the decomp extracts it to orig/GALE01/sys/main.dol);
  SYMBOLS_TXT is the decomp's config/GALE01/symbols.txt.
"""

import re
import struct
import sys

from motion_states import load_dol

# The tables, each with its doc line.
TABLES = [
    ("ftData_SpecialN", "The neutral special's state change."),
    ("ftData_SpecialS", "The side special's."),
    ("ftData_SpecialHi", "The up special's."),
    ("ftData_SpecialLw", "The down special's."),
    ("ftData_SpecialAirN", "The aerial neutral special's."),
    ("ftData_SpecialAirS", "The aerial side special's."),
    ("ftData_SpecialAirHi", "The aerial up special's."),
    ("ftData_SpecialAirLw", "The aerial down special's."),
    ("ftData_OnKnockbackEnter", "Entering knockback."),
    ("ftData_OnKnockbackExit", "Leaving knockback."),
    ("ftData_OnItemPickupExt", "An item picked up."),
    ("ftData_OnItemInvisible", "The held item hidden."),
    ("ftData_OnItemVisible", "The held item shown."),
    ("ftData_OnItemDropExt", "An item dropped."),
    ("ftData_OnItemPickup", "As `ftData_OnItemPickupExt` but for Link's and Young Link's, which "
     "leave their models alone (`ftCommon_8007E7E4` calls these)."),
    ("ftData_OnItemDrop", "As `ftData_OnItemDropExt` but for Link's and Young Link's "
     "(`ftCommon_8007E83C`)."),
]

KINDS = 33


def field(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name.removeprefix("ftData_")).lower()


def main():
    read = load_dol(sys.argv[1])
    names = {}
    tables = {}
    for line in open(sys.argv[2], encoding="utf-8"):
        m = re.match(r"(\S+) = \.(\w+):0x([0-9A-Fa-f]+); // type:(\w+)", line)
        if not m:
            continue
        name, _, addr, kind = m.groups()
        addr = int(addr, 16)
        if kind == "function":
            names[addr] = name
        if name in dict(TABLES):
            tables[name] = addr
    words = {
        name: struct.unpack(f">{KINDS}I", read(tables[name], 4 * KINDS)) for name, _ in TABLES
    }
    out = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/tables/kind_callbacks.py from the executable. Do not edit.",
        "#![allow(clippy::all)]",
        "",
        "/// A fighter kind's callbacks the common code calls by kind, from the executable's tables",
        "/// of one address per kind (0 for none).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct KindCallbacks {",
    ]
    for name, doc in TABLES:
        out.append(f"    /// `{name}`, at {tables[name]:#x}: {doc}")
        out.append(f"    pub {field(name)}: u32,")
    out.append("}")
    out.append("")
    out.append("/// Every fighter kind's callbacks, by kind.")
    out.append(f"pub static KINDS: [KindCallbacks; {KINDS}] = [")
    for k in range(KINDS):
        out.append(f"    // {k}")
        out.append("    KindCallbacks {")
        for name, _ in TABLES:
            w = words[name][k]
            label = names.get(w, "-") if w else "-"
            out.append(f"        {field(name)}: {w:#010x}, // {label}")
        out.append("    },")
    out.append("];")
    out.append("")
    open(sys.argv[3], "w", encoding="utf-8", newline="\n").write("\n".join(out))


if __name__ == "__main__":
    main()
