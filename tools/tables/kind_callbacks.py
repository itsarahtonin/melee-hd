#!/usr/bin/env python3
"""Transcribes the per-character callback tables the common action states dispatch through
(`ftData_SpecialN` and the other `ftData_*` tables of 33 function pointers, one per fighter
kind) from the executable into a Rust table of addresses, which melee-sim calls through
`code::call` until each character's port adds its arms.

Usage: kind_callbacks.py MAIN_DOL SYMBOLS_TXT OUT_RS
  MAIN_DOL is the disc's main.dol (the decomp extracts it to orig/GALE01/sys/main.dol);
  SYMBOLS_TXT is the decomp's config/GALE01/symbols.txt.
"""

import re
import struct
import sys

from motion_states import load_dol

TABLES = [
    "ftData_SpecialN",
    "ftData_SpecialS",
    "ftData_SpecialHi",
    "ftData_SpecialLw",
    "ftData_SpecialAirN",
    "ftData_SpecialAirS",
    "ftData_SpecialAirHi",
    "ftData_SpecialAirLw",
    "ftData_OnKnockbackEnter",
    "ftData_OnKnockbackExit",
]

KINDS = 33


def main():
    read = load_dol(sys.argv[1])
    names = {}
    tables = {}
    for line in open(sys.argv[2], encoding="utf-8"):
        m = re.match(r"(\S+) = \.(\w+):0x([0-9A-Fa-f]+); // type:(\w+)", line)
        if not m:
            continue
        name, _, addr, kind = m.groups()
        addr = int(addr, 16)
        if kind == "function":
            names[addr] = name
        if name in TABLES:
            tables[name] = addr
    out = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/tables/kind_callbacks.py from the executable. Do not edit.",
        "#![allow(clippy::all)]",
        "",
    ]
    for name in TABLES:
        addr = tables[name]
        words = struct.unpack(f">{KINDS}I", read(addr, 4 * KINDS))
        const = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name.removeprefix("ftData_")).upper()
        out.append(f"/// `{name}`, at {addr:#x}: each kind's callback's address, 0 for none.")
        out.append(f"pub static {const}: [u32; {KINDS}] = [")
        for k, w in enumerate(words):
            label = names.get(w, "-") if w else "-"
            out.append(f"    {w:#010x}, // {k}: {label}")
        out.append("];")
        out.append("")
    open(sys.argv[3], "w", encoding="utf-8", newline="\n").write("\n".join(out))


if __name__ == "__main__":
    main()
