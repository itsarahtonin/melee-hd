#!/usr/bin/env python3
"""Transcribes the game's action-state tables (`ftData_MotionStateList`, each character's
`ft*_Init_MotionStateTable`, and the demos' `ftData_803C52A0` and `ft*_Init_UnkMotionStates0`) from the executable into a Rust table: each state's animation,
flags, move id and the addresses of its five callbacks, which melee-sim dispatches on.

Usage: motion_states.py MAIN_DOL SYMBOLS_TXT OUT_RS
  MAIN_DOL is the disc's main.dol (the decomp extracts it to orig/GALE01/sys/main.dol);
  SYMBOLS_TXT is the decomp's config/GALE01/symbols.txt.
"""

import re
import struct
import sys


def load_dol(path):
    b = open(path, 'rb').read()
    offs = struct.unpack('>18I', b[0:72])
    addrs = struct.unpack('>18I', b[72:144])
    sizes = struct.unpack('>18I', b[144:216])
    sections = [(a, o, s) for a, o, s in zip(addrs, offs, sizes) if s]

    def read(addr, n):
        for a, o, s in sections:
            if a <= addr and addr + n <= a + s:
                return b[o + addr - a:o + addr - a + n]
        raise ValueError(f'{addr:#x} not in the DOL')
    return read


def main():
    read = load_dol(sys.argv[1])
    names = {}
    tables = []
    for line in open(sys.argv[2], encoding='utf-8'):
        m = re.match(r'(\S+) = \.(\w+):0x([0-9A-Fa-f]+); // type:(\w+)(?: size:0x([0-9A-Fa-f]+))?', line)
        if not m:
            continue
        name, _, addr, kind, size = m.groups()
        addr = int(addr, 16)
        if kind == 'function':
            names[addr] = name
        # The demos' tables too: the results screen's poses (`ftData_803C52A0`) and the
        # characters' own (`ft*_Init_UnkMotionStates0`).
        if (
            name in ('ftData_MotionStateList', 'ftData_803C52A0')
            or re.match(r'ft\w\w_Init_MotionStateTable$', name)
            or re.match(r'ft\w\w_Init_UnkMotionStates0$', name)
        ):
            tables.append((addr, name, int(size, 16) // 0x20))
    out = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by tools/tables/motion_states.py from the executable. Do not edit.',
        '#![allow(clippy::all)]',
        '',
        'use super::MotionState;',
        'use crate::game::handles::CodeRef;',
        '',
    ]
    entries = []
    for addr, name, n in sorted(tables):
        const = re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper().replace('__', '_')
        out.append(f'/// `{name}`, at {addr:#x}.')
        out.append(f'pub static {const}: [MotionState; {n}] = [')
        for i in range(n):
            w = struct.unpack('>8I', read(addr + 0x20 * i, 0x20))
            cbs = []
            for a in w[3:]:
                if a == 0:
                    cbs.append('None')
                else:
                    cbs.append(f'Some(CodeRef({a:#x}))')
            label = ', '.join(names.get(a, '-') if a else '-' for a in w[3:])
            out.append(f'    // {i}: {label}')
            out.append('    MotionState {')
            out.append(f'        anim_id: {w[0] if w[0] < 0x80000000 else w[0] - (1 << 32)},')
            out.append(f'        flags: {w[1]:#x},')
            out.append(f'        x8: {w[2]:#x},')
            for field, cb in zip(['anim_cb', 'input_cb', 'phys_cb', 'coll_cb', 'cam_cb'], cbs):
                out.append(f'        {field}: {cb},')
            out.append('    },')
        out.append('];')
        out.append('')
        entries.append((addr, const))
    out.append('/// Every table, by its address.')
    out.append(f'pub static TABLES: [(u32, &[MotionState]); {len(entries)}] = [')
    for addr, const in entries:
        out.append(f'    ({addr:#x}, &{const}),')
    out.append('];')
    out.append('')
    open(sys.argv[3], 'w', newline='\n', encoding='utf-8').write('\n'.join(out))
    print(f'{len(entries)} tables')


if __name__ == '__main__':
    main()
